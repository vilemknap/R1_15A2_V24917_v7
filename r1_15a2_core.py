# -*- coding: utf-8 -*-
"""Pure numerical core for R1 STEP 15A2.

The module deliberately has no PTV Visum COM dependency.  It turns official
saved PrT path/path-link rows into a sparse route-incidence operator, solves a
bounded regularised count-space guidance problem, and projects the OD guidance
onto zone production/attraction actuators.

The accepted model is still generated by Visum TG -> TD -> assignment.  The OD
solution produced here is guidance only and is never written as a demand matrix.
"""
from __future__ import annotations

import math
from collections import defaultdict
from copy import deepcopy
from dataclasses import dataclass
from typing import Any, Dict, Iterable, List, Mapping, MutableMapping, Optional, Sequence, Tuple

try:
    import numpy as np
except Exception as exc:  # pragma: no cover - Visum runtime gate handles this
    np = None
    _NUMPY_IMPORT_ERROR = exc
else:
    _NUMPY_IMPORT_ERROR = None

EPS = 1.0e-12

MUTABLE_DSEGS_DEFAULT = (
    "NATIVE_CW", "NATIVE_CW_NOT", "NATIVE_CW_NOTOLL", "NATIVE_CW_NOTOL",
    "NATIVE_CS", "NATIVE_CS_NOT", "NATIVE_CS_NOTOLL", "NATIVE_CS_NOTOL",
)

PASSENGER_DSEGS_DEFAULT = (
    "NATIVE_CF", "NATIVE_CL", "NATIVE_CS", "NATIVE_CS_NOT", "NATIVE_CS_NOTOLL", "NATIVE_CS_NOTOL",
    "NATIVE_CW", "NATIVE_CW_NOT", "NATIVE_CW_NOTOLL", "NATIVE_CW_NOTOL",
    "EXOG_EE_CF", "EXOG_EE_CL", "EXOG_EE_CS", "EXOG_EE_CS_NOT", "EXOG_EE_CS_NOTOLL", "EXOG_EE_CS_NOTOL",
    "EXOG_EE_CW", "EXOG_EE_CW_NOT", "EXOG_EE_CW_NOTOLL", "EXOG_EE_CW_NOTOL",
)


def require_numpy() -> None:
    if np is None:
        raise RuntimeError("R1 15A2 requires NumPy: %r" % (_NUMPY_IMPORT_ERROR,))


def sval(value: Any, default: str = "") -> str:
    if value is None:
        return default
    try:
        return str(value)
    except Exception:
        return default


def fval(value: Any, default: Optional[float] = None) -> Optional[float]:
    if value is None:
        return default
    try:
        if isinstance(value, str):
            text = value.strip().replace("\u00a0", "").replace(" ", "").replace(",", ".")
            if not text or text.lower() in ("nan", "none", "null"):
                return default
            value = text
        out = float(value)
        return out if math.isfinite(out) else default
    except Exception:
        return default


def ival(value: Any, default: Optional[int] = None) -> Optional[int]:
    out = fval(value, None)
    if out is None:
        return default
    try:
        return int(round(out))
    except Exception:
        return default


def norm_code(code: Any) -> str:
    text = sval(code).strip().upper().replace("-", "_").replace(" ", "_")
    while "__" in text:
        text = text.replace("__", "_")
    text = text.replace("_NO_TOLL", "_NOTOLL").replace("_NOTOLL", "_NOT")
    text = text.replace("_NO_T", "_NOT").replace("_NOTOL", "_NOT")
    return text


def family_from_dseg(code: Any) -> str:
    c = norm_code(code)
    if "CW" in c:
        return "WORK"
    if "CS" in c:
        return "SERVICE"
    if c.endswith("_CL") or "LONG" in c:
        return "LONG"
    if c.endswith("_CF") or "FOREIGN" in c:
        return "FOREIGN"
    return "OTHER"


def dseg_layer(code: Any) -> str:
    c = norm_code(code)
    if c.startswith("NATIVE_"):
        return "NATIVE"
    if c.startswith("EXOG_EE_"):
        return "EXOG_EE"
    return "OTHER"


def is_mutable_dseg(code: Any, mutable_codes: Optional[Sequence[str]] = None) -> bool:
    c = norm_code(code)
    allowed = set(norm_code(x) for x in (mutable_codes or MUTABLE_DSEGS_DEFAULT))
    return c in allowed and family_from_dseg(c) in ("WORK", "SERVICE")


def geh(model: float, observed: float) -> float:
    model = max(0.0, float(model))
    observed = max(0.0, float(observed))
    denom = model + observed
    if denom <= EPS:
        return 0.0
    return math.sqrt(2.0 * (model - observed) ** 2 / denom)


def first_value(row: Mapping[str, Any], names: Sequence[str], default: Any = None) -> Any:
    if not row:
        return default
    direct = {sval(k).upper().replace(" ", ""): v for k, v in row.items()}
    for name in names:
        key = sval(name).upper().replace(" ", "")
        if key in direct and direct[key] not in (None, ""):
            return direct[key]
    return default


PATH_ORIGIN_NAMES = ("OrigZoneNo", "OriginZoneNo", "FromZoneNo", "OZoneNo", "ORIGZONENO")
PATH_DEST_NAMES = ("DestZoneNo", "DestinationZoneNo", "ToZoneNo", "DZoneNo", "DESTZONENO")
PATH_INDEX_NAMES = ("Index", "PathIndex", "RouteIndex", "PATHINDEX")
PATH_VOLUME_NAMES = ("Vol(AP)", "Volume(AP)", "Vol", "Volume", "VOL(AP)")
PATHLINK_PATH_INDEX_NAMES = ("PathIndex", "RouteIndex", "PATHINDEX")
PATHLINK_SEQ_NAMES = ("Index", "SeqNo", "Position", "PATHLINKINDEX")
LINK_NO_NAMES = ("LinkNo", "LINKNO", "Link\\No", "LINK.NO")
FROM_NODE_NAMES = ("FromNodeNo", "FROMNODENO", "FromNode\\No", "FROMNODE.NO")
TO_NODE_NAMES = ("ToNodeNo", "TONODENO", "ToNode\\No", "TONODE.NO")


@dataclass(frozen=True)
class PathKey:
    dseg_code: str
    origin: int
    destination: int
    path_index: int


@dataclass(frozen=True)
class ODKey:
    dseg_code: str
    family: str
    origin: int
    destination: int


@dataclass
class SparseOperator:
    row_idx: Any
    col_idx: Any
    values: Any
    n_rows: int
    n_cols: int

    def forward(self, x: Any) -> Any:
        require_numpy()
        if self.values.size == 0:
            return np.zeros(self.n_rows, dtype=float)
        return np.bincount(
            self.row_idx,
            weights=self.values * x[self.col_idx],
            minlength=self.n_rows,
        ).astype(float, copy=False)

    def transpose(self, y: Any) -> Any:
        require_numpy()
        if self.values.size == 0:
            return np.zeros(self.n_cols, dtype=float)
        return np.bincount(
            self.col_idx,
            weights=self.values * y[self.row_idx],
            minlength=self.n_cols,
        ).astype(float, copy=False)


