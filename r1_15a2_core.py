def _path_key_from_row(row: Mapping[str, Any], dseg_override: Optional[str] = None, pathlink: bool = False) -> Optional[PathKey]:
    dseg = norm_code(dseg_override if dseg_override is not None else first_value(row, ("dseg_code", "DSegCode", "DSEGCODE"), ""))
    origin = ival(first_value(row, PATH_ORIGIN_NAMES), None)
    destination = ival(first_value(row, PATH_DEST_NAMES), None)
    index_names = PATHLINK_PATH_INDEX_NAMES if pathlink else PATH_INDEX_NAMES
    path_index = ival(first_value(row, index_names), None)
    if not dseg or origin is None or destination is None or path_index is None:
        return None
    return PathKey(dseg, origin, destination, path_index)


def _link_key_from_row(row: Mapping[str, Any]) -> Optional[Tuple[int, int, int]]:
    no = ival(first_value(row, LINK_NO_NAMES), None)
    fr = ival(first_value(row, FROM_NODE_NAMES), None)
    to = ival(first_value(row, TO_NODE_NAMES), None)
    if no is None or fr is None or to is None:
        return None
    return no, fr, to


def _profile_link_key(profile: Mapping[str, Any]) -> Optional[Tuple[int, int, int]]:
    no = ival(first_value(profile, ("link_no", "LinkNo", "LINKNO")), None)
    fr = ival(first_value(profile, ("from_node_no", "FromNodeNo", "FROMNODENO")), None)
    to = ival(first_value(profile, ("to_node_no", "ToNodeNo", "TONODENO")), None)
    if no is None or fr is None or to is None:
        return None
    return no, fr, to


def _profile_link_keys(profile: Mapping[str, Any]) -> Tuple[Tuple[int, int, int], ...]:
    """Exact profile direction authority: DIRECTED=1, CITY BOTH=2 physical link directions."""
    primary = _profile_link_key(profile)
    if primary is None:
        return ()
    scope = sval(profile.get("observation_direction", "DIRECTED")).upper()
    if scope == "DIRECTED":
        return (primary,)
    if scope != "BOTH":
        raise ValueError("Unsupported CountLocation direction scope: " + scope)
    rev = (
        ival(profile.get("reverse_link_no"), None),
        ival(profile.get("reverse_from_node_no"), None),
        ival(profile.get("reverse_to_node_no"), None),
    )
    if (None in rev or rev == primary or rev != (primary[0], primary[2], primary[1])):
        raise ValueError("Invalid BOTH reverse physical link authority")
    return primary, rev


def parse_official_path_rows(path_rows: Sequence[Mapping[str, Any]]) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    """Normalize official Visum PrT path list rows.

    Duplicate keys are combined only when their metadata are consistent.  Path
    volume is summed, which also makes concatenated per-DSeg exports safe.
    """
    by_key: Dict[PathKey, Dict[str, Any]] = {}
    invalid = 0
    negative = 0
    for raw in path_rows:
        key = _path_key_from_row(raw)
        if key is None:
            invalid += 1
            continue
        volume = fval(first_value(raw, PATH_VOLUME_NAMES), None)
        if volume is None:
            invalid += 1
            continue
        if volume < -EPS:
            negative += 1
            continue
        rec = by_key.get(key)
        if rec is None:
            rec = {
                "path_key": key,
                "dseg_code": key.dseg_code,
                "family": family_from_dseg(key.dseg_code),
                "layer": dseg_layer(key.dseg_code),
                "origin": key.origin,
                "destination": key.destination,
                "path_index": key.path_index,
                "volume": 0.0,
                "raw_rows": 0,
            }
            by_key[key] = rec
        rec["volume"] += max(0.0, float(volume))
        rec["raw_rows"] += 1
    rows = sorted(by_key.values(), key=lambda r: (r["dseg_code"], r["origin"], r["destination"], r["path_index"]))
    summary = {
        "input_rows": len(path_rows),
        "normalized_paths": len(rows),
        "invalid_rows": invalid,
        "negative_volume_rows": negative,
        "total_path_volume": sum(r["volume"] for r in rows),
    }
    return rows, summary


def build_actual_path_incidence(
    path_rows: Sequence[Mapping[str, Any]],
    pathlink_rows: Sequence[Mapping[str, Any]],
    profiles: Sequence[Mapping[str, Any]],
    mutable_dsegs: Optional[Sequence[str]] = None,
    actuatable_zone_nos: Optional[Sequence[int]] = None,
    mutable_relation_policy: str = "BOTH_ENDPOINTS_ACTUATABLE",
    station_link_to_labels: Optional[Mapping[Tuple[int, int, int], Sequence[str]]] = None,
    pair_authority: Optional[Sequence[Mapping[str, Any]]] = None,
    skip_wiggly_pair_paths: bool = True,
) -> Dict[str, Any]:
    """Build exact current path incidence from official Visum saved routes.

    Link-count incidence permits multiplicity.  If a path traverses a directed
    counted link twice, its coefficient is 2 rather than 1.  Ordered station-pair
    observations are optional and are derived from the actual saved link sequence,
    never from a reconstructed shortest path.
    """
    require_numpy()
    paths, path_summary = parse_official_path_rows(path_rows)
    path_by_key: Dict[PathKey, Dict[str, Any]] = {r["path_key"]: r for r in paths}

    profile_link_map: Dict[Tuple[int, int, int], List[int]] = defaultdict(list)
    profile_meta: List[Dict[str, Any]] = []
    for idx, p in enumerate(profiles):
        pp = dict(p)
        pp["_profile_index"] = idx
        pp["_link_key"] = _profile_link_key(p)
        pp["_link_keys"] = _profile_link_keys(p)
        profile_meta.append(pp)
        for directed_key in pp["_link_keys"]:
            profile_link_map[directed_key].append(idx)

    mutable_codes = set(norm_code(x) for x in (mutable_dsegs or MUTABLE_DSEGS_DEFAULT))
    actuatable_set = None if actuatable_zone_nos is None else set(int(x) for x in actuatable_zone_nos)
    relation_policy = sval(mutable_relation_policy or "BOTH_ENDPOINTS_ACTUATABLE").strip().upper()
    if relation_policy not in ("BOTH_ENDPOINTS_ACTUATABLE", "ALL_MUTABLE_RELATIONS"):
        raise ValueError("Unsupported mutable_relation_policy=%s" % relation_policy)

    # projection_base_variables retain all current NATIVE WORK/SERVICE OD totals.
    # Solver variables can be a strict subset (normally both endpoints must be
    # legitimate ADD actuators).  Keeping the full base catalog prevents an OD
    # subset from overstating relative P/A changes during projection.
    projection_base_by_od: Dict[ODKey, int] = {}
    projection_base_variables: List[Dict[str, Any]] = []
    path_to_projection_base: Dict[PathKey, int] = {}
    projection_base_q: List[float] = []

    variable_by_od: Dict[ODKey, int] = {}
    variable_meta: List[Dict[str, Any]] = []
    path_to_variable: Dict[PathKey, int] = {}
    q_od: List[float] = []
    excluded_scope_path_count = 0
    excluded_scope_path_volume = 0.0
    excluded_scope_od_keys: set = set()

    for path in paths:
        code = norm_code(path["dseg_code"])
        family = family_from_dseg(code)
        if code not in mutable_codes or family not in ("WORK", "SERVICE"):
            continue
        od = ODKey(code, family, int(path["origin"]), int(path["destination"]))

        bidx = projection_base_by_od.get(od)
        if bidx is None:
            bidx = len(projection_base_variables)
            projection_base_by_od[od] = bidx
            projection_base_variables.append({
                "base_variable_index": bidx,
                "dseg_code": od.dseg_code,
                "family": od.family,
                "origin": od.origin,
                "destination": od.destination,
                "q_current": 0.0,
                "path_count": 0,
                "actuatable_relation": 0,
            })
            projection_base_q.append(0.0)
        projection_base_q[bidx] += float(path["volume"])
        projection_base_variables[bidx]["q_current"] = projection_base_q[bidx]
        projection_base_variables[bidx]["path_count"] += 1
        path_to_projection_base[path["path_key"]] = bidx

        if relation_policy == "ALL_MUTABLE_RELATIONS" or actuatable_set is None:
            relation_is_actuatable = True
        else:
            relation_is_actuatable = od.origin in actuatable_set and od.destination in actuatable_set
        if not relation_is_actuatable:
            excluded_scope_path_count += 1
            excluded_scope_path_volume += float(path["volume"])
            excluded_scope_od_keys.add(od)
            continue
        projection_base_variables[bidx]["actuatable_relation"] = 1

        vidx = variable_by_od.get(od)
        if vidx is None:
            vidx = len(variable_meta)
            variable_by_od[od] = vidx
            variable_meta.append({
                "variable_index": vidx,
                "dseg_code": od.dseg_code,
                "family": od.family,
                "origin": od.origin,
                "destination": od.destination,
                "q_current": 0.0,
                "path_count": 0,
                "actuatable_relation": 1,
            })
            q_od.append(0.0)
        q_od[vidx] += float(path["volume"])
        variable_meta[vidx]["q_current"] = q_od[vidx]
        variable_meta[vidx]["path_count"] += 1
        path_to_variable[path["path_key"]] = vidx

    full_profile_model = np.zeros(len(profile_meta), dtype=float)
    native_ws_profile_model = np.zeros(len(profile_meta), dtype=float)
    mutable_profile_model = np.zeros(len(profile_meta), dtype=float)
    through_by_pair: Dict[Tuple[int, int], float] = defaultdict(float)
    path_profile_multiplicity: Dict[Tuple[PathKey, int], int] = defaultdict(int)
    path_station_hits: Dict[PathKey, List[Tuple[int, str]]] = defaultdict(list)
    path_has_link_rows: set = set()
    orphan_pathlink_rows = 0
    invalid_pathlink_rows = 0

    station_map = station_link_to_labels or {}
    for raw in pathlink_rows:
        key = _path_key_from_row(raw, pathlink=True)
        if key is None:
            invalid_pathlink_rows += 1
            continue
        path = path_by_key.get(key)
        if path is None:
            orphan_pathlink_rows += 1
            continue
        link_key = _link_key_from_row(raw)
        if link_key is None:
            invalid_pathlink_rows += 1
            continue
        path_has_link_rows.add(key)
        for pidx in profile_link_map.get(link_key, ()):
            path_profile_multiplicity[(key, pidx)] += 1
        if station_map and link_key in station_map:
            seq = ival(first_value(raw, PATHLINK_SEQ_NAMES), 0) or 0
            for label in station_map.get(link_key, ()):
                path_station_hits[key].append((seq, sval(label).strip().upper()))

    for (path_key, pidx), multiplicity in path_profile_multiplicity.items():
        path = path_by_key[path_key]
        volume = float(path["volume"]) * float(multiplicity)
        full_profile_model[pidx] += volume
        if path_key in path_to_projection_base:
            native_ws_profile_model[pidx] += volume
        vidx = path_to_variable.get(path_key)
        if vidx is not None:
            mutable_profile_model[pidx] += volume
            through_by_pair[(pidx, vidx)] += volume

    q = np.asarray(q_od, dtype=float)
    row_idx: List[int] = []
    col_idx: List[int] = []
    p_values: List[float] = []
    through_values: List[float] = []
    for (pidx, vidx), through in through_by_pair.items():
        denom = q[vidx]
        if denom <= EPS:
            continue
        row_idx.append(pidx)
        col_idx.append(vidx)
        through_values.append(float(through))
        p_values.append(float(through) / float(denom))

    incidence = SparseOperator(
        np.asarray(row_idx, dtype=np.int64),
        np.asarray(col_idx, dtype=np.int64),
        np.asarray(through_values, dtype=float),  # absolute derivative wrt relative OD change
        len(profile_meta),
        len(variable_meta),
    )

    total_path_volume = float(sum(float(p.get("volume", 0.0) or 0.0) for p in paths))
    covered_path_volume = float(sum(float(path_by_key[k].get("volume", 0.0) or 0.0) for k in path_has_link_rows if k in path_by_key))

    # Optional exact ordered station-pair incidence from actual path-link sequences.
    pair_result: Dict[str, Any] = {
        "enabled": bool(pair_authority and station_map),
        "observations": [],
        "row_idx": np.zeros(0, dtype=np.int64),
        "col_idx": np.zeros(0, dtype=np.int64),
        "values": np.zeros(0, dtype=float),
        "full_model": np.zeros(0, dtype=float),
        "mutable_model": np.zeros(0, dtype=float),
        "wiggly_skipped_paths": 0,
    }
    if pair_authority and station_map:
        obs_meta: List[Dict[str, Any]] = []
        pair_to_idx: Dict[Tuple[str, str], int] = {}
        for raw in pair_authority:
            o = sval(first_value(raw, ("origin_label", "origin_station_key", "origin"))).strip().upper()
            d = sval(first_value(raw, ("destination_label", "destination_station_key", "destination"))).strip().upper()
            if not o or not d or o == d:
                continue
            obs = fval(first_value(raw, ("rpdi_value", "observed", "value")), None)
            if obs is None:
                continue
            pair = (o, d)
            if pair in pair_to_idx:
                continue
            idx = len(obs_meta)
            pair_to_idx[pair] = idx
            obs_meta.append({
                "pair_index": idx,
                "origin_station": o,
                "destination_station": d,
                "observed": float(obs),
                "role": sval(first_value(raw, ("role",), "DIAGNOSTIC")).upper() or "DIAGNOSTIC",
            })
        pair_full = np.zeros(len(obs_meta), dtype=float)
        pair_mut = np.zeros(len(obs_meta), dtype=float)
        pair_through: Dict[Tuple[int, int], float] = defaultdict(float)
        wiggly = 0
        for key, hits in path_station_hits.items():
            if not hits:
                continue
            hits = sorted(hits, key=lambda x: x[0])
            labels = [h[1] for h in hits]
            duplicate = len(labels) != len(set(labels))
            if duplicate and skip_wiggly_pair_paths:
                wiggly += 1
                continue
            first_pos: Dict[str, int] = {}
            for seq, label in hits:
                if label not in first_pos:
                    first_pos[label] = seq
            path = path_by_key.get(key)
            if path is None:
                continue
            vol = float(path["volume"])
            vidx = path_to_variable.get(key)
            labs = list(first_pos.keys())
            for o in labs:
                for d in labs:
                    if o == d or first_pos[o] >= first_pos[d]:
                        continue
                    pidx = pair_to_idx.get((o, d))
                    if pidx is None:
                        continue
                    pair_full[pidx] += vol
                    if vidx is not None:
                        pair_mut[pidx] += vol
                        pair_through[(pidx, vidx)] += vol
        pr, pc, pv = [], [], []
        for (pidx, vidx), through in pair_through.items():
            pr.append(pidx); pc.append(vidx); pv.append(float(through))
        for meta, model, mut in zip(obs_meta, pair_full, pair_mut):
            meta["model"] = float(model)
            meta["mutable_model"] = float(mut)
            meta["residual"] = float(meta["observed"] - model)
            meta["geh"] = geh(model, meta["observed"])
        pair_result = {
            "enabled": True,
            "observations": obs_meta,
            "row_idx": np.asarray(pr, dtype=np.int64),
            "col_idx": np.asarray(pc, dtype=np.int64),
            "values": np.asarray(pv, dtype=float),
            "full_model": pair_full,
            "mutable_model": pair_mut,
            "wiggly_skipped_paths": wiggly,
        }

    return {
        "profiles": profile_meta,
        "variables": variable_meta,
        "projection_base_variables": projection_base_variables,
        "q_current": q,
        "incidence": incidence,
        "incidence_share": np.asarray(p_values, dtype=float),
        "incidence_through": np.asarray(through_values, dtype=float),
        "full_profile_model_from_paths": full_profile_model,
        "native_ws_profile_model_from_paths": native_ws_profile_model,
        "mutable_profile_model_from_paths": mutable_profile_model,
        "path_summary": path_summary,
        "path_count": len(paths),
        "pathlink_count": len(pathlink_rows),
        "paths_with_link_rows": len(path_has_link_rows),
        "path_link_coverage": (len(path_has_link_rows) / float(max(1, len(paths)))),
        "total_path_volume": total_path_volume,
        "covered_path_volume": covered_path_volume,
        "path_link_volume_coverage": (covered_path_volume / total_path_volume if total_path_volume > EPS else 0.0),
        "orphan_pathlink_rows": orphan_pathlink_rows,
        "invalid_pathlink_rows": invalid_pathlink_rows,
        "variable_count": len(variable_meta),
        "projection_base_variable_count": len(projection_base_variables),
        "incidence_nnz": int(len(row_idx)),
        "actuator_scope": {
            "mutable_relation_policy": relation_policy,
            "actuatable_zone_count": (len(actuatable_set) if actuatable_set is not None else None),
            "excluded_mutable_path_count": int(excluded_scope_path_count),
            "excluded_mutable_path_volume": float(excluded_scope_path_volume),
            "excluded_mutable_od_count": int(len(excluded_scope_od_keys)),
        },
        "pair_observations": pair_result,
    }


def merge_actual_path_incidence_batches(results: Sequence[Mapping[str, Any]]) -> Dict[str, Any]:
    """Merge independently built per-DSeg incidence batches.

    The official path lists can be very large.  Production orchestration exports
    and reduces one demand segment at a time, then merges only sparse operators
    and compact OD catalogs.  This keeps peak memory bounded by the largest
    single DSeg export instead of all selected DSegs combined.
    """
    require_numpy()
    batches = [r for r in results if r is not None]
    if not batches:
        raise ValueError("No incidence batches to merge.")
    profiles = list(batches[0]["profiles"])
    n_profiles = len(profiles)

    def profile_identity(row):
        return (
            ival(first_value(row, ["countlocation_no", "NO", "No"]), None),
            ival(first_value(row, ["link_no", "LINKNO", "LinkNo"]), None),
            ival(first_value(row, ["from_node_no", "FROMNODENO", "FromNodeNo"]), None),
            ival(first_value(row, ["to_node_no", "TONODENO", "ToNodeNo"]), None),
            sval(first_value(row, ["role", "R1_ROLE"], "")).strip().upper(),
        )

    profile_ids = [profile_identity(x) for x in profiles]
    variables: List[Dict[str, Any]] = []
    projection_base_variables: List[Dict[str, Any]] = []
    q_parts = []
    rr_parts = []; cc_parts = []; vv_parts = []
    share_parts = []; through_parts = []
    full = np.zeros(n_profiles, dtype=float)
    native_ws = np.zeros(n_profiles, dtype=float)
    mutable = np.zeros(n_profiles, dtype=float)
    path_count = pathlink_count = paths_with_link_rows = 0
    total_path_volume = covered_path_volume = 0.0
    orphan_pathlink_rows = invalid_pathlink_rows = 0
    input_path_rows = normalized_paths = invalid_path_rows = negative_path_rows = 0
    actuator_scope = {
        "mutable_relation_policy": None,
        "actuatable_zone_count": None,
        "excluded_mutable_path_count": 0,
        "excluded_mutable_path_volume": 0.0,
        "excluded_mutable_od_count": 0,
    }

    pair_enabled = False
    pair_observations: List[Dict[str, Any]] = []
    pair_full = None; pair_mut = None
    pair_rr = []; pair_cc = []; pair_vv = []
    pair_wiggly = 0

    col_offset = 0
    base_offset = 0
    for batch_no, r in enumerate(batches, start=1):
        batch_profiles = list(r.get("profiles", []))
        if len(batch_profiles) != n_profiles:
            raise ValueError("Incidence batch profile-count mismatch.")
        if [profile_identity(x) for x in batch_profiles] != profile_ids:
            raise ValueError("Incidence batch profile-order/identity mismatch.")
        op: SparseOperator = r["incidence"]
        local_vars = list(r.get("variables", []))
        for local_idx, meta in enumerate(local_vars):
            m = dict(meta)
            m["batch_no"] = batch_no
            m["batch_variable_index"] = int(meta.get("variable_index", local_idx))
            m["variable_index"] = col_offset + local_idx
            variables.append(m)
        local_base = list(r.get("projection_base_variables", local_vars))
        for local_idx, meta in enumerate(local_base):
            m = dict(meta)
            m["batch_no"] = batch_no
            m["batch_base_variable_index"] = int(meta.get("base_variable_index", local_idx))
            m["base_variable_index"] = base_offset + local_idx
            projection_base_variables.append(m)
        q_parts.append(np.asarray(r.get("q_current", []), dtype=float))
        if op.values.size:
            rr_parts.append(np.asarray(op.row_idx, dtype=np.int64))
            cc_parts.append(np.asarray(op.col_idx, dtype=np.int64) + col_offset)
            vv_parts.append(np.asarray(op.values, dtype=float))
            share_parts.append(np.asarray(r.get("incidence_share", []), dtype=float))
            through_parts.append(np.asarray(r.get("incidence_through", op.values), dtype=float))
        full += np.asarray(r.get("full_profile_model_from_paths", np.zeros(n_profiles)), dtype=float)
        native_ws += np.asarray(r.get("native_ws_profile_model_from_paths", np.zeros(n_profiles)), dtype=float)
        mutable += np.asarray(r.get("mutable_profile_model_from_paths", np.zeros(n_profiles)), dtype=float)
        path_count += int(r.get("path_count", 0) or 0)
        pathlink_count += int(r.get("pathlink_count", 0) or 0)
        paths_with_link_rows += int(r.get("paths_with_link_rows", 0) or 0)
        total_path_volume += float(r.get("total_path_volume", 0.0) or 0.0)
        covered_path_volume += float(r.get("covered_path_volume", 0.0) or 0.0)
        orphan_pathlink_rows += int(r.get("orphan_pathlink_rows", 0) or 0)
        invalid_pathlink_rows += int(r.get("invalid_pathlink_rows", 0) or 0)
        ps = r.get("path_summary") or {}
        input_path_rows += int(ps.get("input_rows", 0) or 0)
        normalized_paths += int(ps.get("normalized_paths", 0) or 0)
        invalid_path_rows += int(ps.get("invalid_rows", 0) or 0)
        negative_path_rows += int(ps.get("negative_volume_rows", 0) or 0)
        sc = r.get("actuator_scope") or {}
        if actuator_scope["mutable_relation_policy"] is None:
            actuator_scope["mutable_relation_policy"] = sc.get("mutable_relation_policy")
            actuator_scope["actuatable_zone_count"] = sc.get("actuatable_zone_count")
        elif (
            actuator_scope["mutable_relation_policy"] != sc.get("mutable_relation_policy")
            or actuator_scope["actuatable_zone_count"] != sc.get("actuatable_zone_count")
        ):
            raise ValueError("Incidence batch actuator-scope mismatch.")
        actuator_scope["excluded_mutable_path_count"] += int(sc.get("excluded_mutable_path_count", 0) or 0)
        actuator_scope["excluded_mutable_path_volume"] += float(sc.get("excluded_mutable_path_volume", 0.0) or 0.0)
        actuator_scope["excluded_mutable_od_count"] += int(sc.get("excluded_mutable_od_count", 0) or 0)

        pr = r.get("pair_observations") or {}
        if pr.get("enabled"):
            local_obs = list(pr.get("observations") or [])
            if not pair_enabled:
                pair_enabled = True
                pair_observations = [dict(x) for x in local_obs]
                pair_full = np.zeros(len(local_obs), dtype=float)
                pair_mut = np.zeros(len(local_obs), dtype=float)
            elif len(local_obs) != len(pair_observations):
                raise ValueError("Pair-observation authority mismatch between batches.")
            else:
                def pair_identity(x):
                    return (
                        sval(x.get("origin_station", x.get("from_station", ""))).strip().upper(),
                        sval(x.get("destination_station", x.get("to_station", ""))).strip().upper(),
                        sval(x.get("role", "")).strip().upper(),
                        float(fval(x.get("observed"), 0.0) or 0.0),
                    )
                if [pair_identity(x) for x in local_obs] != [pair_identity(x) for x in pair_observations]:
                    raise ValueError("Pair-observation order/identity mismatch between batches.")
            pair_full += np.asarray(pr.get("full_model", np.zeros(len(local_obs))), dtype=float)
            pair_mut += np.asarray(pr.get("mutable_model", np.zeros(len(local_obs))), dtype=float)
            lrr = np.asarray(pr.get("row_idx", []), dtype=np.int64)
            lcc = np.asarray(pr.get("col_idx", []), dtype=np.int64)
            lvv = np.asarray(pr.get("values", []), dtype=float)
            if lvv.size:
                pair_rr.append(lrr); pair_cc.append(lcc + col_offset); pair_vv.append(lvv)
            pair_wiggly += int(pr.get("wiggly_skipped_paths", 0) or 0)

        col_offset += len(local_vars)
        base_offset += len(local_base)

    row_idx = np.concatenate(rr_parts) if rr_parts else np.zeros(0, dtype=np.int64)
    col_idx = np.concatenate(cc_parts) if cc_parts else np.zeros(0, dtype=np.int64)
    values = np.concatenate(vv_parts) if vv_parts else np.zeros(0, dtype=float)
    shares = np.concatenate(share_parts) if share_parts else np.zeros(0, dtype=float)
    through = np.concatenate(through_parts) if through_parts else np.zeros(0, dtype=float)
    q = np.concatenate(q_parts) if q_parts else np.zeros(0, dtype=float)
    incidence = SparseOperator(row_idx, col_idx, values, n_profiles, len(variables))

    pair_result: Dict[str, Any] = {
        "enabled": False, "observations": [],
        "row_idx": np.zeros(0, dtype=np.int64), "col_idx": np.zeros(0, dtype=np.int64),
        "values": np.zeros(0, dtype=float), "full_model": np.zeros(0, dtype=float),
        "mutable_model": np.zeros(0, dtype=float), "wiggly_skipped_paths": 0,
    }
    if pair_enabled:
        for meta, model, mut in zip(pair_observations, pair_full, pair_mut):
            meta["model"] = float(model)
            meta["mutable_model"] = float(mut)
            meta["residual"] = float(meta.get("observed", 0.0) - model)
            meta["geh"] = geh(model, float(meta.get("observed", 0.0)))
        pair_result = {
            "enabled": True, "observations": pair_observations,
            "row_idx": np.concatenate(pair_rr) if pair_rr else np.zeros(0, dtype=np.int64),
            "col_idx": np.concatenate(pair_cc) if pair_cc else np.zeros(0, dtype=np.int64),
            "values": np.concatenate(pair_vv) if pair_vv else np.zeros(0, dtype=float),
            "full_model": pair_full, "mutable_model": pair_mut,
            "wiggly_skipped_paths": pair_wiggly,
        }

    return {
        "profiles": profiles,
        "variables": variables,
        "projection_base_variables": projection_base_variables,
        "q_current": q,
        "incidence": incidence,
        "incidence_share": shares,
        "incidence_through": through,
        "full_profile_model_from_paths": full,
        "native_ws_profile_model_from_paths": native_ws,
        "mutable_profile_model_from_paths": mutable,
        "path_summary": {
            "input_rows": input_path_rows, "normalized_paths": normalized_paths,
            "invalid_rows": invalid_path_rows, "negative_volume_rows": negative_path_rows,
            "total_path_volume": total_path_volume,
        },
        "path_count": path_count,
        "pathlink_count": pathlink_count,
        "paths_with_link_rows": paths_with_link_rows,
        "path_link_coverage": paths_with_link_rows / float(max(1, path_count)),
        "total_path_volume": total_path_volume,
        "covered_path_volume": covered_path_volume,
        "path_link_volume_coverage": covered_path_volume / total_path_volume if total_path_volume > EPS else 0.0,
        "orphan_pathlink_rows": orphan_pathlink_rows,
        "invalid_pathlink_rows": invalid_pathlink_rows,
        "variable_count": len(variables),
        "projection_base_variable_count": len(projection_base_variables),
        "incidence_nnz": int(values.size),
        "actuator_scope": actuator_scope,
        "batch_count": len(batches),
        "pair_observations": pair_result,
    }


def _build_entries_by_profile(operator: SparseOperator) -> List[List[Tuple[int, float]]]:
    out: List[List[Tuple[int, float]]] = [[] for _ in range(operator.n_rows)]
    for r, c, v in zip(operator.row_idx.tolist(), operator.col_idx.tolist(), operator.values.tolist()):
        out[int(r)].append((int(c), float(v)))
    return out


def prepare_guidance_problem(
    incidence_result: Mapping[str, Any],
    config: Mapping[str, Any],
    include_pair_observations: bool = False,
) -> GuidanceProblem:
    """Create a sparse bounded least-squares guidance problem.

    Positive-only mode uses underloaded CAL profiles as drivers.  Overloaded and
    already-good CAL profiles are zero-change penalties, so the solver seeks OD
    increases that help deficits without loading protected or over-routed links.
    """
    require_numpy()
    profiles = list(incidence_result["profiles"])
    variables = list(incidence_result["variables"])
    operator: SparseOperator = incidence_result["incidence"]
    q = np.asarray(incidence_result["q_current"], dtype=float)
    entries = _build_entries_by_profile(operator)

    mode = sval(config.get("guidance_mode", "POSITIVE_ONLY")).upper()
    positive_only = mode != "SIGNED"
    calibration_role = sval(config.get("calibration_role", "CALIBRATION")).upper()
    min_driver_geh = float(config.get("min_driver_geh", 10.0))
    min_driver_abs = float(config.get("min_driver_abs_residual", 300.0))
    min_mutable_share = float(config.get("min_mutable_share", config.get("min_native_share", 0.35)))
    protected_geh = float(config.get("protected_geh", 5.0))
    overroute_geh = float(config.get("overroute_penalty_geh", 5.0))
    observed_floor = float(config.get("observed_weight_floor", 100.0))
    driver_mult = float(config.get("driver_weight_multiplier", 1.0))
    over_mult = float(config.get("overroute_weight_multiplier", 1.5))
    protected_mult = float(config.get("protected_weight_multiplier", 3.0))
    neutral_mult = float(config.get("neutral_weight_multiplier", 0.35))

    objective_rows: List[Dict[str, Any]] = []
    original_profile_indices: List[int] = []
    dropped_objective_rows: List[Dict[str, Any]] = []
    for pidx, p in enumerate(profiles):
        role = sval(first_value(p, ("role",), "")).upper()
        if role != calibration_role:
            continue
        observed = fval(first_value(p, ("observed",)), 0.0) or 0.0
        model = fval(first_value(p, ("model",)), 0.0) or 0.0
        # Never trust a transported GEH value as an actuator.  Recompute it from
        # the live observed/model values carried by the current 12D run.
        g = geh(model, observed)
        residual = observed - model
        # The actuator is NATIVE WORK/SERVICE only.  12D's native_share_model
        # also includes CL/CF and is therefore not a valid mutability share here.
        path_scope_model = float(incidence_result["full_profile_model_from_paths"][pidx])
        path_mut = float(incidence_result["mutable_profile_model_from_paths"][pidx])
        share_denom_mode = sval(config.get("mutable_share_denominator", "12D_TOTAL_MODEL")).upper()
        if share_denom_mode == "12D_TOTAL_MODEL":
            mutable_share_denominator = max(0.0, float(model))
        elif share_denom_mode == "EXPORTED_PATH_SCOPE":
            mutable_share_denominator = path_scope_model
        else:
            raise ValueError("Unsupported mutable_share_denominator=%s" % share_denom_mode)
        mutable_share = path_mut / mutable_share_denominator if mutable_share_denominator > EPS else 0.0
        if observed <= 0.0:
            dropped_objective_rows.append({
                "source": "CSD", "source_index": pidx, "kind": "ZERO_OBS_DIAGNOSTIC",
                "reason": "OBSERVED_NOT_POSITIVE", "observed": observed, "model": model,
                "residual": residual, "geh": g, "mutable_share": mutable_share,
                "mutable_share_denominator": mutable_share_denominator,
                "path_scope_model": path_scope_model,
            })
            continue
        source_w = fval(first_value(p, ("profile_weight",), 1.0), None)
        if source_w is None or source_w <= 0:
            raise ValueError("Invalid R1 Weight in actual-path guidance")
        base_w = math.sqrt(2.0 * source_w / max(observed_floor, observed + model))
        if g < protected_geh:
            objective_rows.append({
                "source": "CSD", "source_index": pidx, "kind": "PROTECTED_ZERO_CHANGE",
                "target": 0.0, "weight": base_w * protected_mult,
                "observed": observed, "model": model, "residual": residual, "geh": g,
                "mutable_share": mutable_share,
                "mutable_share_denominator": mutable_share_denominator,
                "path_scope_model": path_scope_model,
            })
            original_profile_indices.append(pidx)
            # A protected profile must never simultaneously become a driver,
            # even when its absolute residual is large at high traffic volume.
            continue
        # Over-routed profiles protect the candidate even when the directly
        # actuatable WORK/SERVICE share is small.  A low mutable share means the
        # profile must not *drive* a demand increase; it is not permission to
        # ignore damage caused by candidate OD relations that do traverse it.
        if positive_only and residual < 0.0 and g >= overroute_geh:
            objective_rows.append({
                "source": "CSD", "source_index": pidx, "kind": "OVERROUTE_ZERO_CHANGE",
                "target": 0.0, "weight": base_w * over_mult,
                "observed": observed, "model": model, "residual": residual, "geh": g,
                "mutable_share": mutable_share,
                "mutable_share_denominator": mutable_share_denominator,
                "path_scope_model": path_scope_model,
            })
            original_profile_indices.append(pidx)
            continue
        if mutable_share < min_mutable_share:
            # Low-actuator-share counts cannot drive demand.  They remain a
            # zero-change constraint with neutral weight unless already caught
            # above as a protected or over-routed profile.
            objective_rows.append({
                "source": "CSD", "source_index": pidx, "kind": "LOW_MUTABLE_SHARE_ZERO_CHANGE",
                "target": 0.0, "weight": base_w * neutral_mult,
                "observed": observed, "model": model, "residual": residual, "geh": g,
                "mutable_share": mutable_share,
                "mutable_share_denominator": mutable_share_denominator,
                "path_scope_model": path_scope_model,
            })
            original_profile_indices.append(pidx)
            continue
        if positive_only:
            if residual > 0.0 and (g >= min_driver_geh or residual >= min_driver_abs):
                objective_rows.append({
                    "source": "CSD", "source_index": pidx, "kind": "UNDERLOAD_DRIVER",
                    "target": residual, "weight": base_w * driver_mult,
                    "observed": observed, "model": model, "residual": residual, "geh": g,
                    "mutable_share": mutable_share,
                    "mutable_share_denominator": mutable_share_denominator,
                    "path_scope_model": path_scope_model,
                })
                original_profile_indices.append(pidx)
            elif g >= protected_geh:
                objective_rows.append({
                    "source": "CSD", "source_index": pidx, "kind": "NEUTRAL_ZERO_CHANGE",
                    "target": 0.0, "weight": base_w * neutral_mult,
                    "observed": observed, "model": model, "residual": residual, "geh": g,
                    "mutable_share": mutable_share,
                    "mutable_share_denominator": mutable_share_denominator,
                    "path_scope_model": path_scope_model,
                })
                original_profile_indices.append(pidx)
        else:
            if (g >= min_driver_geh or abs(residual) >= min_driver_abs):
                objective_rows.append({
                    "source": "CSD", "source_index": pidx, "kind": "SIGNED_DRIVER",
                    "target": residual, "weight": base_w * driver_mult,
                    "observed": observed, "model": model, "residual": residual, "geh": g,
                    "mutable_share": mutable_share,
                    "mutable_share_denominator": mutable_share_denominator,
                    "path_scope_model": path_scope_model,
                })
                original_profile_indices.append(pidx)

    # Optional ordered kordon observations.  They are diagnostic unless explicitly
    # marked CALIBRATION by the caller/config.
    pair = incidence_result.get("pair_observations") or {}
    pair_entries: List[List[Tuple[int, float]]] = []
    if include_pair_observations and pair.get("enabled"):
        pair_op = SparseOperator(
            np.asarray(pair["row_idx"], dtype=np.int64),
            np.asarray(pair["col_idx"], dtype=np.int64),
            np.asarray(pair["values"], dtype=float),
            len(pair.get("observations") or []),
            len(variables),
        )
        pair_entries = _build_entries_by_profile(pair_op)
        pair_mult = float(config.get("kordon_pair_weight_multiplier", 0.5))
        for pair_idx, obs_row in enumerate(pair.get("observations") or []):
            if sval(obs_row.get("role", "DIAGNOSTIC")).upper() != calibration_role:
                continue
            observed = float(obs_row.get("observed", 0.0) or 0.0)
            model = float(obs_row.get("model", 0.0) or 0.0)
            residual = observed - model
            g = geh(model, observed)
            if observed <= 0.0:
                continue
            base_w = math.sqrt(2.0 / max(observed_floor, observed + model)) * pair_mult
            if positive_only and residual <= 0.0:
                target = 0.0; kind = "KORDON_OVERROUTE_ZERO_CHANGE"
            else:
                target = residual; kind = "KORDON_DRIVER"
            objective_rows.append({
                "source": "KORDON_PAIR", "source_index": pair_idx, "kind": kind,
                "target": target, "weight": base_w,
                "observed": observed, "model": model, "residual": residual, "geh": g,
                "origin_station": obs_row.get("origin_station", ""),
                "destination_station": obs_row.get("destination_station", ""),
            })
            original_profile_indices.append(-1 - pair_idx)

    if not any(r["kind"] in ("UNDERLOAD_DRIVER", "SIGNED_DRIVER", "KORDON_DRIVER") for r in objective_rows):
        raise ValueError("No eligible CALIBRATION driver observations for path-incidence guidance.")

    # Candidate variables need enough current volume and at least one driver exposure.
    min_q = float(config.get("min_od_volume", 5.0))
    driver_exposure = np.zeros(len(variables), dtype=float)
    for obj in objective_rows:
        if obj["kind"] not in ("UNDERLOAD_DRIVER", "SIGNED_DRIVER", "KORDON_DRIVER"):
            continue
        if obj["source"] == "CSD":
            ent = entries[int(obj["source_index"])]
        else:
            ent = pair_entries[int(obj["source_index"])]
        w = float(obj["weight"])
        for c, v in ent:
            driver_exposure[c] += abs(w * v)
    eligible = np.where((q >= min_q) & (driver_exposure > 0.0))[0]
    max_vars = int(config.get("max_solver_variables", 50000))
    if max_vars > 0 and eligible.size > max_vars:
        order = np.argsort(driver_exposure[eligible])[::-1][:max_vars]
        eligible = eligible[order]
    eligible = np.sort(eligible)
    if eligible.size == 0:
        raise ValueError("No mutable OD variables meet volume/incidence gates.")
    old_to_new = {int(old): int(new) for new, old in enumerate(eligible.tolist())}

    rr: List[int] = []
    cc: List[int] = []
    vv: List[float] = []
    kept_obj_rows: List[Dict[str, Any]] = []
    kept_original: List[int] = []
    for obj, original_idx in zip(objective_rows, original_profile_indices):
        ent = entries[int(obj["source_index"])] if obj["source"] == "CSD" else pair_entries[int(obj["source_index"])]
        row_no = len(kept_obj_rows)
        n_added = 0
        for old_c, value in ent:
            new_c = old_to_new.get(int(old_c))
            if new_c is None or abs(value) <= EPS:
                continue
            rr.append(row_no); cc.append(new_c); vv.append(float(value)); n_added += 1
        if n_added > 0:
            kept_obj_rows.append(dict(obj, operator_nnz=n_added))
            kept_original.append(original_idx)
        else:
            dropped_objective_rows.append(dict(
                obj,
                reason="NO_ELIGIBLE_MUTABLE_OD_INCIDENCE_AFTER_FILTER",
                operator_nnz=0,
            ))

    if not kept_obj_rows:
        raise ValueError("Objective rows have no incidence after OD variable filtering.")
    if not any(r["kind"] in ("UNDERLOAD_DRIVER", "SIGNED_DRIVER", "KORDON_DRIVER") for r in kept_obj_rows):
        raise ValueError("All driver observations lost their eligible mutable OD incidence after filtering.")

    target = np.asarray([float(r["target"]) for r in kept_obj_rows], dtype=float)
    row_weight = np.asarray([float(r["weight"]) for r in kept_obj_rows], dtype=float)
    selected_q = q[eligible]
    q_ref = float(np.median(selected_q[selected_q > 0])) if np.any(selected_q > 0) else 1.0
    tiny_power = float(config.get("tiny_od_penalty_power", 0.5))
    tiny_scale = np.power(q_ref / np.maximum(selected_q, min_q), tiny_power)
    ridge = float(config.get("ridge_lambda", 0.15)) * tiny_scale
    l1 = float(config.get("l1_lambda", 0.002)) * tiny_scale
    max_up = float(config.get("max_od_relative_up", 0.08))
    max_down = float(config.get("max_od_relative_down", 0.04))
    lower = np.zeros_like(selected_q) if positive_only else np.full_like(selected_q, -max_down)
    upper = np.full_like(selected_q, max_up)

    selected_meta = []
    for new_idx, old_idx in enumerate(eligible.tolist()):
        m = dict(variables[int(old_idx)])
        m["original_variable_index"] = int(old_idx)
        m["solver_variable_index"] = int(new_idx)
        m["driver_exposure"] = float(driver_exposure[int(old_idx)])
        selected_meta.append(m)

    op = SparseOperator(
        np.asarray(rr, dtype=np.int64),
        np.asarray(cc, dtype=np.int64),
        np.asarray(vv, dtype=float),
        len(kept_obj_rows),
        len(selected_meta),
    )
    return GuidanceProblem(
        operator=op,
        target=target,
        row_weight=row_weight,
        ridge_diag=np.asarray(ridge, dtype=float),
        l1_diag=np.asarray(l1, dtype=float),
        lower=lower,
        upper=upper,
        variable_meta=selected_meta,
        objective_rows=kept_obj_rows,
        original_profile_indices=np.asarray(kept_original, dtype=np.int64),
        dropped_objective_rows=dropped_objective_rows,
        selection_summary={
            "calibration_profile_count": sum(1 for p in profiles if sval(first_value(p, ("role",), "")).upper() == calibration_role),
            "objective_rows_before_incidence_filter": len(objective_rows),
            "objective_rows_kept": len(kept_obj_rows),
            "objective_rows_dropped": len(dropped_objective_rows),
            "driver_rows_kept": sum(1 for r in kept_obj_rows if r["kind"] in ("UNDERLOAD_DRIVER", "SIGNED_DRIVER", "KORDON_DRIVER")),
            "penalty_rows_kept": sum(1 for r in kept_obj_rows if r["kind"] not in ("UNDERLOAD_DRIVER", "SIGNED_DRIVER", "KORDON_DRIVER")),
            "all_mutable_od_variables": len(variables),
            "eligible_solver_variables": len(selected_meta),
            "min_mutable_share": min_mutable_share,
            "mutable_share_denominator": sval(config.get("mutable_share_denominator", "12D_TOTAL_MODEL")).upper(),
        },
    )


def _smooth_gradient(problem: GuidanceProblem, x: Any) -> Tuple[Any, Any]:
    pred = problem.operator.forward(x)
    weighted_normal_resid = (problem.row_weight ** 2) * (pred - problem.target)
    grad = problem.operator.transpose(weighted_normal_resid) + problem.ridge_diag * x
    return grad, pred


def _smooth_hessian_apply(problem: GuidanceProblem, x: Any) -> Any:
    ax = problem.operator.forward(x)
    return problem.operator.transpose((problem.row_weight ** 2) * ax) + problem.ridge_diag * x


def estimate_lipschitz(problem: GuidanceProblem, iterations: int = 30) -> float:
    require_numpy()
    n = problem.operator.n_cols
    if n <= 0:
        return 1.0
    v = np.ones(n, dtype=float) / math.sqrt(float(n))
    eig = 1.0
    for _ in range(max(3, int(iterations))):
        hv = _smooth_hessian_apply(problem, v)
        norm = float(np.linalg.norm(hv))
        if not math.isfinite(norm) or norm <= EPS:
            return max(1.0, float(np.max(problem.ridge_diag)) if problem.ridge_diag.size else 1.0)
        v = hv / norm
        eig = float(np.dot(v, _smooth_hessian_apply(problem, v)))
    return max(1.0e-9, eig * 1.05)


def guidance_objective(problem: GuidanceProblem, x: Any) -> float:
    pred = problem.operator.forward(x)
    r = problem.row_weight * (pred - problem.target)
    return 0.5 * float(np.dot(r, r)) + 0.5 * float(np.dot(problem.ridge_diag * x, x)) + float(np.dot(problem.l1_diag, np.abs(x)))


def solve_guidance(problem: GuidanceProblem, config: Mapping[str, Any]) -> GuidanceResult:
    require_numpy()
    n = problem.operator.n_cols
    x = np.zeros(n, dtype=float)
    y = x.copy()
    t = 1.0
    max_iter = int(config.get("solver_max_iter", 1200))
    tol = float(config.get("solver_tolerance", 1.0e-7))
    check_every = int(config.get("solver_check_every", 10))
    lipschitz = estimate_lipschitz(problem, int(config.get("power_iterations", 35)))
    step = 1.0 / lipschitz
    history: List[Dict[str, float]] = []
    obj0 = guidance_objective(problem, x)
    prev_obj = obj0
    converged = False
    final_iter = 0

    for it in range(1, max_iter + 1):
        grad, _ = _smooth_gradient(problem, y)
        z = y - step * grad
        # Proximal L1 + box projection.
        thresh = step * problem.l1_diag
        z = np.sign(z) * np.maximum(0.0, np.abs(z) - thresh)
        x_new = np.minimum(problem.upper, np.maximum(problem.lower, z))
        t_new = 0.5 * (1.0 + math.sqrt(1.0 + 4.0 * t * t))
        y = x_new + ((t - 1.0) / t_new) * (x_new - x)
        x = x_new
        t = t_new
        final_iter = it
        if it == 1 or it % max(1, check_every) == 0 or it == max_iter:
            obj = guidance_objective(problem, x)
            rel = abs(prev_obj - obj) / max(1.0, abs(prev_obj))
            history.append({"iteration": float(it), "objective": float(obj), "relative_change": float(rel)})
            if rel <= tol:
                converged = True
                prev_obj = obj
                break
            # Monotone restart if FISTA overshoots materially.
            if obj > prev_obj * (1.0 + 1.0e-8):
                y = x.copy(); t = 1.0
            prev_obj = obj

    pred = problem.operator.forward(x)
    return GuidanceResult(
        x=x,
        predicted_change=pred,
        residual_after_linear=problem.target - pred,
        objective_initial=float(obj0),
        objective_final=float(guidance_objective(problem, x)),
        iterations=final_iter,
        converged=converged,
        lipschitz=float(lipschitz),
        history=history,
    )


def _project_family(
    zone_nos: Sequence[int],
    origins: Any,
    destinations: Any,
    targets: Any,
    weights: Any,
    config: Mapping[str, Any],
) -> Tuple[Any, Any, Dict[str, Any]]:
    require_numpy()
    zone_to_idx = {int(z): i for i, z in enumerate(zone_nos)}
    oidx = np.asarray([zone_to_idx[int(z)] for z in origins], dtype=np.int64)
    didx = np.asarray([zone_to_idx[int(z)] for z in destinations], dtype=np.int64)
    target = np.asarray(targets, dtype=float)
    w = np.asarray(weights, dtype=float)
    n = len(zone_nos)
    lam = float(config.get("projection_ridge_lambda", 0.30))
    max_up = float(config.get("max_add_log_up", 0.04))
    max_down = float(config.get("max_add_log_down", 0.02))
    positive_only = sval(config.get("guidance_mode", "POSITIVE_ONLY")).upper() != "SIGNED"
    lo = 0.0 if positive_only else -max_down
    hi = max_up

    # Estimate a safe Lipschitz upper bound from weighted row degrees.
    w2 = w * w
    deg_o = np.bincount(oidx, weights=w2, minlength=n)
    deg_d = np.bincount(didx, weights=w2, minlength=n)
    lipschitz = max(1.0e-9, 2.0 * float(max(np.max(deg_o), np.max(deg_d), 1.0)) + lam)
    step = 1.0 / lipschitz
    up = np.zeros(n, dtype=float)
    ua = np.zeros(n, dtype=float)
    max_iter = int(config.get("projection_max_iter", 1200))
    tol = float(config.get("projection_tolerance", 1.0e-8))
    prev_obj = None
    converged = False
    for it in range(1, max_iter + 1):
        pred = up[oidx] + ua[didx]
        e = w2 * (pred - target)
        gp = np.bincount(oidx, weights=e, minlength=n) + lam * up
        ga = np.bincount(didx, weights=e, minlength=n) + lam * ua
        up_new = np.minimum(hi, np.maximum(lo, up - step * gp))
        ua_new = np.minimum(hi, np.maximum(lo, ua - step * ga))
        up, ua = up_new, ua_new
        if it == 1 or it % 20 == 0 or it == max_iter:
            pred = up[oidx] + ua[didx]
            obj = 0.5 * float(np.dot(w * (pred - target), w * (pred - target))) + 0.5 * lam * float(np.dot(up, up) + np.dot(ua, ua))
            if prev_obj is not None and abs(prev_obj - obj) / max(1.0, abs(prev_obj)) <= tol:
                converged = True
                break
            prev_obj = obj
    pred = up[oidx] + ua[didx]
    rmse = math.sqrt(float(np.dot(w2, (pred - target) ** 2)) / max(EPS, float(np.sum(w2))))
    return up, ua, {"iterations": it, "converged": converged, "weighted_rmse": rmse, "objective": float(prev_obj or 0.0)}


def project_guidance_to_add(
    problem: GuidanceProblem,
    result: GuidanceResult,
    zone_nos: Sequence[int],
    config: Mapping[str, Any],
    all_variable_meta: Optional[Sequence[Mapping[str, Any]]] = None,
) -> ProjectionResult:
    """Project latent OD guidance onto legitimate P/A actuators.

    The default ``MARGINALS`` method does not fit ``x_ij = u_i + v_j``.  That
    additive fit overstates a uniform change in a doubly-constrained model: if
    both production and attraction margins grow by 2 %, total trips grow by
    roughly 2 %, not 4 %.  Instead we aggregate the guided absolute OD changes
    to desired origin and destination margin changes and convert those ratios
    to bounded log multipliers.  This preserves equality of total production
    and attraction guidance by construction.

    ``ADDITIVE_LOG_FIT`` is retained only as an explicit research fallback.
    """
    require_numpy()
    min_abs = float(config.get("min_od_guidance_for_projection", 1.0e-5))
    method = sval(config.get("projection_method", "MARGINALS")).upper()
    rows: List[Dict[str, Any]] = []
    summaries: List[Dict[str, Any]] = []
    rmse_num = 0.0
    rmse_den = 0.0
    all_meta = list(all_variable_meta or problem.variable_meta)
    zone_to_idx = {int(z): i for i, z in enumerate(zone_nos)}
    for family in ("WORK", "SERVICE"):
        idx = [i for i, m in enumerate(problem.variable_meta) if m.get("family") == family and abs(float(result.x[i])) >= min_abs]
        if not idx:
            continue
        if method == "ADDITIVE_LOG_FIT":
            origins = [int(problem.variable_meta[i]["origin"]) for i in idx]
            destinations = [int(problem.variable_meta[i]["destination"]) for i in idx]
            targets = np.asarray([float(result.x[i]) for i in idx], dtype=float)
            q = np.asarray([max(0.0, float(problem.variable_meta[i].get("q_current", 0.0))) for i in idx], dtype=float)
            weights = np.sqrt(np.maximum(q, float(config.get("projection_min_volume_weight", 1.0))))
            up, ua, sm = _project_family(zone_nos, origins, destinations, targets, weights, config)
            sm.update({"family": family, "od_rows": len(idx), "method": method})
            summaries.append(sm)
            rmse_num += sm["weighted_rmse"] ** 2 * float(np.sum(weights ** 2))
            rmse_den += float(np.sum(weights ** 2))
            for role, vec in (("PROD", up), ("ATT", ua)):
                for z, val in zip(zone_nos, vec.tolist()):
                    if abs(val) < float(config.get("min_add_log_step", 1.0e-5)):
                        continue
                    rows.append({
                        "zone_no": int(z), "family": family, "role": role,
                        "projection_method": method,
                        "base_margin_volume": "", "guided_margin_delta": "",
                        "raw_relative_margin_change": "", "raw_log_step": float(val),
                        "log_step": float(val), "multiplier": float(math.exp(val)),
                    })
            continue

        if method != "MARGINALS":
            raise ValueError("Unsupported projection_method=%s" % method)

        n = len(zone_nos)
        base_prod = np.zeros(n, dtype=float)
        base_att = np.zeros(n, dtype=float)
        for meta in all_meta:
            if sval(meta.get("family", "")).upper() != family:
                continue
            o = ival(meta.get("origin"), None); d = ival(meta.get("destination"), None)
            if o not in zone_to_idx or d not in zone_to_idx:
                continue
            q0 = max(0.0, float(meta.get("q_current", 0.0) or 0.0))
            base_prod[zone_to_idx[o]] += q0
            base_att[zone_to_idx[d]] += q0

        delta_prod = np.zeros(n, dtype=float)
        delta_att = np.zeros(n, dtype=float)
        guided_abs_total = 0.0
        for i in idx:
            meta = problem.variable_meta[i]
            o = int(meta["origin"]); d = int(meta["destination"])
            if o not in zone_to_idx or d not in zone_to_idx:
                continue
            q0 = max(0.0, float(meta.get("q_current", 0.0) or 0.0))
            delta = q0 * float(result.x[i])
            delta_prod[zone_to_idx[o]] += delta
            delta_att[zone_to_idx[d]] += delta
            guided_abs_total += delta

        gain = float(config.get("projection_gain", 1.0))
        ridge_volume = max(0.0, float(config.get("projection_ridge_volume", 0.0)))
        max_up = float(config.get("max_add_log_up", 0.04))
        max_down = float(config.get("max_add_log_down", 0.02))
        positive_only = sval(config.get("guidance_mode", "POSITIVE_ONLY")).upper() != "SIGNED"
        lo = 0.0 if positive_only else -max_down
        hi = max_up
        min_step = float(config.get("min_add_log_step", 1.0e-5))
        sq_err = 0.0
        sq_weight = 0.0
        projected_totals: Dict[str, float] = {}
        role_specs: Dict[str, Dict[str, Any]] = {}
        min_weight = float(config.get("projection_min_volume_weight", 1.0))

        for role, base, delta in (("PROD", base_prod, delta_prod), ("ATT", base_att, delta_att)):
            raw_rel = np.zeros(n, dtype=float)
            shrink = np.ones(n, dtype=float)
            valid = base > EPS
            raw_rel[valid] = delta[valid] / base[valid]
            if ridge_volume > 0.0:
                shrink[valid] = base[valid] / (base[valid] + ridge_volume)
            requested_rel = gain * shrink * raw_rel
            requested_rel = np.maximum(-0.95, requested_rel)
            raw_log = np.log1p(requested_rel)
            raw_log[~valid] = 0.0
            role_specs[role] = {
                "base": base, "delta": delta, "raw_rel": raw_rel,
                "shrink": shrink, "raw_log": raw_log, "valid": valid,
            }

        def role_total(spec: Mapping[str, Any], beta: float) -> float:
            applied = np.minimum(hi, np.maximum(lo, float(beta) * spec["raw_log"]))
            return float(np.sum(spec["base"] * np.expm1(applied)))

        role_totals_at_one = dict((role, role_total(spec, 1.0)) for role, spec in role_specs.items())
        balance_scales = {"PROD": 1.0, "ATT": 1.0}
        common_projected_total = None
        if positive_only:
            # Keep generated total production and attraction changes equal after
            # zone-level shrinkage and caps.  The smaller feasible side defines
            # the common trust-region total; the other side is reduced by a
            # monotone scalar bisection.
            common_projected_total = min(
                max(0.0, role_totals_at_one.get("PROD", 0.0)),
                max(0.0, role_totals_at_one.get("ATT", 0.0)),
            )
            for role, spec in role_specs.items():
                total_one = role_totals_at_one.get(role, 0.0)
                if total_one <= common_projected_total + 1.0e-10:
                    balance_scales[role] = 1.0
                    continue
                low_beta, high_beta = 0.0, 1.0
                for _ in range(70):
                    mid = 0.5 * (low_beta + high_beta)
                    if role_total(spec, mid) < common_projected_total:
                        low_beta = mid
                    else:
                        high_beta = mid
                balance_scales[role] = 0.5 * (low_beta + high_beta)

        for role, spec in role_specs.items():
            beta = float(balance_scales.get(role, 1.0))
            applied_logs = np.minimum(hi, np.maximum(lo, beta * spec["raw_log"]))
            projected_deltas = spec["base"] * np.expm1(applied_logs)
            projected_total = float(np.sum(projected_deltas))
            projected_totals[role] = projected_total
            for pos, z in enumerate(zone_nos):
                b = float(spec["base"][pos])
                if b <= EPS:
                    continue
                raw_log = float(spec["raw_log"][pos])
                applied_log = float(applied_logs[pos])
                projected_delta = float(projected_deltas[pos])
                weight = max(b, min_weight)
                sq_err += weight * (applied_log - raw_log) ** 2
                sq_weight += weight
                if abs(applied_log) < min_step:
                    continue
                rows.append({
                    "zone_no": int(z), "family": family, "role": role,
                    "projection_method": method,
                    "base_margin_volume": b,
                    "guided_margin_delta": float(spec["delta"][pos]),
                    "raw_relative_margin_change": float(spec["raw_rel"][pos]),
                    "projection_gain": gain,
                    "projection_shrink": float(spec["shrink"][pos]),
                    "pa_total_balance_scale": beta,
                    "raw_log_step": raw_log,
                    "log_step": applied_log,
                    "multiplier": float(math.exp(applied_log)),
                    "projected_margin_delta": projected_delta,
                })

        family_rmse = math.sqrt(sq_err / max(EPS, sq_weight)) if sq_weight > 0.0 else 0.0
        sm = {
            "family": family,
            "method": method,
            "guided_od_rows": len(idx),
            "all_family_od_rows": sum(1 for m in all_meta if sval(m.get("family", "")).upper() == family),
            "current_family_volume": float(np.sum(base_prod)),
            "guided_absolute_total_change": float(guided_abs_total),
            "guided_prod_total_change": float(np.sum(delta_prod)),
            "guided_att_total_change": float(np.sum(delta_att)),
            "projected_prod_total_change": float(projected_totals.get("PROD", 0.0)),
            "projected_att_total_change": float(projected_totals.get("ATT", 0.0)),
            "common_projected_total_change": common_projected_total,
            "prod_total_balance_scale": float(balance_scales.get("PROD", 1.0)),
            "att_total_balance_scale": float(balance_scales.get("ATT", 1.0)),
            "projected_pa_total_abs_gap": abs(float(projected_totals.get("PROD", 0.0)) - float(projected_totals.get("ATT", 0.0))),
            "weighted_rmse": family_rmse,
            "converged": True,
            "iterations": 0,
        }
        summaries.append(sm)
        rmse_num += family_rmse ** 2 * sq_weight
        rmse_den += sq_weight
    rows.sort(key=lambda r: abs(float(r["log_step"])), reverse=True)
    return ProjectionResult(rows, summaries, math.sqrt(rmse_num / max(EPS, rmse_den)) if rmse_den > 0 else 0.0)


def path_parity_rows(
    profiles: Sequence[Mapping[str, Any]],
    path_model: Sequence[float],
    model_fields: Optional[Sequence[str]] = None,
) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    fields = list(model_fields or [])
    for p, pm in zip(profiles, path_model):
        if fields:
            model = sum(float(fval(first_value(p, (name,)), 0.0) or 0.0) for name in fields)
            model_basis = "+".join(fields)
        else:
            model = fval(first_value(p, ("model",)), 0.0) or 0.0
            model_basis = "model"
        diff = float(pm) - model
        denom = max(1.0, abs(model))
        out.append({
            "countlocation_no": first_value(p, ("countlocation_no", "NO"), ""),
            "role": first_value(p, ("role",), ""),
            "link_no": first_value(p, ("link_no",), ""),
            "from_node_no": first_value(p, ("from_node_no",), ""),
            "to_node_no": first_value(p, ("to_node_no",), ""),
            "model_12d": model,
            "model_12d_basis": model_basis,
            "model_from_saved_paths": float(pm),
            "diff": diff,
            "abs_diff": abs(diff),
            "relative_abs_diff": abs(diff) / denom,
        })
    return out


def summarize_path_parity(rows: Sequence[Mapping[str, Any]], config: Mapping[str, Any]) -> Dict[str, Any]:
    vals = [float(r.get("relative_abs_diff", 0.0) or 0.0) for r in rows if float(r.get("model_12d", 0.0) or 0.0) >= float(config.get("parity_min_model", 100.0))]
    abs_vals = [float(r.get("abs_diff", 0.0) or 0.0) for r in rows]
    if not vals:
        return {"status": "NO_ELIGIBLE_PROFILES", "passes": False, "n": 0}
    arr = np.asarray(vals, dtype=float)
    p95 = float(np.quantile(arr, 0.95))
    p99 = float(np.quantile(arr, 0.99))
    max_rel = float(np.max(arr))
    max_abs = float(max(abs_vals) if abs_vals else 0.0)
    pass_p95 = p95 <= float(config.get("parity_p95_relative_tolerance", 0.02))
    pass_p99 = p99 <= float(config.get("parity_p99_relative_tolerance", 0.05))
    passes = bool(pass_p95 and pass_p99)
    return {
        "status": "PASS" if passes else "FAIL",
        "passes": passes,
        "n": int(arr.size),
        "mean_relative_abs_diff": float(np.mean(arr)),
        "p95_relative_abs_diff": p95,
        "p99_relative_abs_diff": p99,
        "max_relative_abs_diff": max_rel,
        "max_abs_diff": max_abs,
    }


CSD_OBJECTIVE_WEIGHTED_MEAN_GEH = "WEIGHTED_MEAN_GEH"
CSD_OBJECTIVE_WEIGHTED_MEAN_GEH2 = "WEIGHTED_MEAN_GEH2"


def csd_objective_metric(config: Mapping[str, Any]) -> str:
    """Resolve the CAL profile objective while preserving legacy releases.

    Releases before V2.4.9.3 did not declare a metric and therefore retain the
    historical weighted mean GEH-squared objective.  V2.4.9.3 opts in to the
    methodologically intended weighted mean GEH objective.
    """
    spec = config.get("csd_calibration_objective", {}) or {}
    raw = sval(spec.get("metric", config.get("csd_objective_metric",
                                              CSD_OBJECTIVE_WEIGHTED_MEAN_GEH2))).strip().upper()
    aliases = {
        "GEH": CSD_OBJECTIVE_WEIGHTED_MEAN_GEH,
        "MEAN_GEH": CSD_OBJECTIVE_WEIGHTED_MEAN_GEH,
        "WEIGHTED_GEH": CSD_OBJECTIVE_WEIGHTED_MEAN_GEH,
        "GEH2": CSD_OBJECTIVE_WEIGHTED_MEAN_GEH2,
        "MEAN_GEH2": CSD_OBJECTIVE_WEIGHTED_MEAN_GEH2,
        "WEIGHTED_GEH2": CSD_OBJECTIVE_WEIGHTED_MEAN_GEH2,
    }
    metric = aliases.get(raw, raw)
    if metric not in (CSD_OBJECTIVE_WEIGHTED_MEAN_GEH,
                       CSD_OBJECTIVE_WEIGHTED_MEAN_GEH2):
        raise ValueError("UNSUPPORTED_CSD_CALIBRATION_OBJECTIVE:%s" % raw)
    return metric


