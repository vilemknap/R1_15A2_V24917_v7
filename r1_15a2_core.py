def csd_metrics(rows: Sequence[Mapping[str, Any]], role: str = "CALIBRATION", exclude_zero_obs: bool = True) -> Dict[str, Any]:
    selected = []
    role_u = sval(role).upper()
    for r in rows:
        if sval(first_value(r, ("role",), "")).upper() != role_u:
            continue
        obs = fval(first_value(r, ("observed",)), 0.0) or 0.0
        if exclude_zero_obs and obs <= 0.0:
            continue
        model = fval(first_value(r, ("model",)), 0.0) or 0.0
        g = geh(model, obs)
        weight = fval(first_value(r, ("profile_weight",), 1.0), None)
        if weight is None or weight <= 0:
            raise ValueError("Invalid authoritative R1 Weight for CAL observation")
        selected.append((obs, model, g, weight))
    if not selected:
        return {
            "role": role_u, "n": 0,
            "objective_geh_mean_weighted": float("inf"),
            "objective_geh2_mean": float("inf"),
            "profile_sum_role": "DIAGNOSTIC_ONLY_PROFILE_PASSAGE_CHECKSUM",
            "profile_sum_unique_trip_interpretation_allowed": False,
        }
    obs = np.asarray([x[0] for x in selected], dtype=float)
    model = np.asarray([x[1] for x in selected], dtype=float)
    gs = np.asarray([x[2] for x in selected], dtype=float)
    diff = model - obs
    weights = np.asarray([x[3] for x in selected], dtype=float)
    return {
        "role": role_u,
        "n": int(len(selected)),
        "obs_sum": float(np.sum(obs)),
        "model_sum": float(np.sum(model)),
        "model_obs_ratio": float(np.sum(model) / max(EPS, np.sum(obs))),
        "profile_sum_role": "DIAGNOSTIC_ONLY_PROFILE_PASSAGE_CHECKSUM",
        "profile_sum_unique_trip_interpretation_allowed": False,
        "profile_sum_note": (
            "A trip may cross multiple observed profiles; sums are not unique-trip "
            "or total-demand estimates."),
        "rmse": float(math.sqrt(np.mean(diff ** 2))),
        "mae": float(np.mean(np.abs(diff))),
        "objective_geh_mean_weighted": float(np.average(gs, weights=weights)),
        "objective_geh2_mean": float(np.average(gs ** 2, weights=weights)),
        "objective_weight_sum": float(np.sum(weights)),
        "geh_mean": float(np.mean(gs)),
        "geh_lt5": int(np.sum(gs < 5.0)),
        "geh_lt10": int(np.sum(gs < 10.0)),
        "geh_ge20": int(np.sum(gs >= 20.0)),
        "geh_ge30": int(np.sum(gs >= 30.0)),
    }


def early_exploration_policy(
    config: Mapping[str, Any],
    policy_scope: str = "GENERATION",
) -> Dict[str, Any] | None:
    """Resolve the active baseline-relative acceptance policy.

    Demand uses the reviewed V2.4.9.12 policy keyed by outer demand cycle.
    V2.4.9.13 adds an independent Supply route-choice policy keyed by supply
    cycle.  Keeping the two clocks separate prevents a long TG/TD search from
    consuming the exploratory budget intended for ADDVAL route-choice tuning.
    """
    scope = sval(policy_scope or config.get("runtime_acceptance_scope", "GENERATION")).strip().upper()

    if scope.startswith("SUPPLY"):
        raw = config.get("supply_route_choice_acceptance", {}) if isinstance(config, Mapping) else {}
        if not isinstance(raw, Mapping) or raw.get("enabled") is not True:
            return None
        cycle = ival(config.get("runtime_acceptance_supply_cycle"), None)
        if cycle is None:
            cycle = ival(config.get("runtime_acceptance_outer_cycle"), None)
        if cycle is None or cycle <= 0:
            return None
        through = int(raw.get("through_supply_cycle", 0))
        if through <= 0 or cycle > through:
            return None
        scoped = raw.get("supply", {}) or {}
        severity = raw.get("severity", {}) or {}
        if not isinstance(scoped, Mapping) or not isinstance(severity, Mapping):
            raise ValueError("Invalid supply route-choice acceptance policy")
        return {
            "enabled": True,
            "mode": sval(raw.get("mode", "BASELINE_RELATIVE_ROUTE_CHOICE_EXPLORATION")).upper(),
            "outer_cycle": cycle,
            "supply_cycle": cycle,
            "through_outer_cycle": through,
            "through_supply_cycle": through,
            "scope": "SUPPLY",
            "scoped": dict(scoped),
            "severity": dict(severity),
            "best_so_far": dict(raw.get("best_so_far", {}) or {}),
            "policy_id": sval(raw.get("policy_id", "V24913_SUPPLY_ROUTE_CHOICE_POLICY")),
        }

    raw = config.get("early_exploration_acceptance", {}) if isinstance(config, Mapping) else {}
    if not isinstance(raw, Mapping) or raw.get("enabled") is not True:
        return None
    cycle = ival(config.get("runtime_acceptance_outer_cycle"), None)
    if cycle is None or cycle <= 0:
        return None
    through = int(raw.get("through_outer_cycle", 0))
    if through <= 0 or cycle > through:
        return None
    scope_key = "td" if scope.startswith("TD") else "generation"
    scoped = raw.get(scope_key, {}) or {}
    severity = raw.get("severity", {}) or {}
    if not isinstance(scoped, Mapping) or not isinstance(severity, Mapping):
        raise ValueError("Invalid early-exploration acceptance policy")
    return {
        "enabled": True,
        "mode": sval(raw.get("mode", "NONMONOTONIC_PARETO_WITH_BEST_SO_FAR")).upper(),
        "outer_cycle": cycle,
        "through_outer_cycle": through,
        "scope": scope_key.upper(),
        "scoped": dict(scoped),
        "severity": dict(severity),
        "best_so_far": dict(raw.get("best_so_far", {}) or {}),
    }


def geh_severity_metrics(
    rows: Sequence[Mapping[str, Any]],
    power: float = 2.0,
) -> Dict[str, Any]:
    """Continuous weighted CAL severity above GEH20/30 plus bucket counts."""
    if not math.isfinite(power) or power <= 0.0:
        raise ValueError("Invalid GEH severity-score power")
    values = []
    for row in rows:
        if sval(first_value(row, ("role",), "")).upper() != "CALIBRATION":
            continue
        obs = float(fval(first_value(row, ("observed",)), 0.0) or 0.0)
        if obs <= 0.0:
            continue
        model = float(fval(first_value(row, ("model",)), 0.0) or 0.0)
        weight = fval(first_value(row, ("profile_weight",), 1.0), None)
        if weight is None or weight <= 0.0:
            raise ValueError("Invalid authoritative R1 Weight for CAL observation")
        values.append((geh(model, obs), float(weight)))
    if not values:
        return {
            "n": 0, "weight_sum": 0.0, "geh_ge20": 0, "geh_ge30": 0,
            "geh_ge35": 0, "geh_ge40": 0, "max_geh": 0.0,
            "severity20": 0.0, "severity30": 0.0, "power": power,
        }
    gs = np.asarray([x[0] for x in values], dtype=float)
    weights = np.asarray([x[1] for x in values], dtype=float)
    denom = max(EPS, float(np.sum(weights)))
    return {
        "n": int(len(values)),
        "weight_sum": float(np.sum(weights)),
        "geh_ge20": int(np.sum(gs >= 20.0)),
        "geh_ge30": int(np.sum(gs >= 30.0)),
        "geh_ge35": int(np.sum(gs >= 35.0)),
        "geh_ge40": int(np.sum(gs >= 40.0)),
        "max_geh": float(np.max(gs)),
        "severity20": float(np.sum(weights * np.maximum(gs - 20.0, 0.0) ** power) / denom),
        "severity30": float(np.sum(weights * np.maximum(gs - 30.0, 0.0) ** power) / denom),
        "power": power,
    }


def protected_profile_guard(
    before_rows: Sequence[Mapping[str, Any]],
    after_rows: Sequence[Mapping[str, Any]],
    config: Mapping[str, Any],
    policy_scope: str = "GENERATION",
) -> Dict[str, Any]:
    key = lambda r: sval(first_value(r, ("countlocation_no", "obs_id", "code"), ""))
    bmap = {key(r): r for r in before_rows if key(r)}
    amap = {key(r): r for r in after_rows if key(r)}
    early = early_exploration_policy(config, policy_scope)
    if early is not None:
        sev = early["severity"]
        protected = float(sev.get("protected_before_geh", 5.0))
        hard = float(sev.get("protected_after_hard_geh", 20.0))
        max_hard = int(sev.get("max_protected_catastrophic", 0))
        details = []
        for k, b in bmap.items():
            a = amap.get(k)
            if a is None or sval(first_value(b, ("role",), "")).upper() != "CALIBRATION":
                continue
            bobs = float(fval(first_value(b, ("observed",)), 0.0) or 0.0)
            aobs = float(fval(first_value(a, ("observed",)), 0.0) or 0.0)
            if bobs <= 0.0 or aobs <= 0.0:
                continue
            bg = geh(float(fval(first_value(b, ("model",)), 0.0) or 0.0), bobs)
            ag = geh(float(fval(first_value(a, ("model",)), 0.0) or 0.0), aobs)
            if bg < protected and ag >= hard:
                details.append({"profile": k, "before_geh": bg, "after_geh": ag,
                                "classification": "PROTECTED_CATASTROPHIC"})
        return {
            "passes": len(details) <= max_hard,
            "mode": "EARLY_EXPLORATION_CATASTROPHIC_ONLY",
            "policy_scope": early["scope"],
            "protected_before_geh": protected,
            "protected_after_hard_geh": hard,
            "protected_to_warn": 0,
            "protected_to_hard": len(details),
            "max_protected_catastrophic": max_hard,
            "details": details,
        }
    protected = float(config.get("protected_geh", 5.0))
    warn = float(config.get("protected_warn_geh", 10.0))
    hard = float(config.get("protected_hard_geh", 30.0))
    warn_count = 0
    hard_count = 0
    details = []
    for k, b in bmap.items():
        a = amap.get(k)
        if a is None:
            continue
        if sval(first_value(b, ("role",), "")).upper() != "CALIBRATION":
            continue
        bobs = fval(first_value(b, ("observed",)), 0.0) or 0.0
        bmodel = fval(first_value(b, ("model",)), 0.0) or 0.0
        aobs = fval(first_value(a, ("observed",)), 0.0) or 0.0
        amodel = fval(first_value(a, ("model",)), 0.0) or 0.0
        if bobs <= 0.0 or aobs <= 0.0:
            continue
        bg = geh(bmodel, bobs)
        ag = geh(amodel, aobs)
        if bg < protected and ag >= warn:
            warn_count += 1
            if ag >= hard:
                hard_count += 1
            details.append({"profile": k, "before_geh": bg, "after_geh": ag, "hard": int(ag >= hard)})
    return {
        "passes": hard_count <= int(config.get("max_protected_to_hard", 0)) and warn_count <= int(config.get("max_protected_to_warn", 3)),
        "mode": "INHERITED_PROTECTED_PROFILE_GUARD",
        "protected_to_warn": warn_count,
        "protected_to_hard": hard_count,
        "details": details,
    }

def observation_set_guard(
    before_rows: Sequence[Mapping[str, Any]],
    after_rows: Sequence[Mapping[str, Any]],
) -> Dict[str, Any]:
    """Ensure that acceptance compares the same observation authority.

    A candidate must not become acceptable because a CountLocation disappeared,
    changed role, or its observed value changed between the before/after runs.
    """
    def key(row: Mapping[str, Any]) -> str:
        return sval(first_value(row, ("countlocation_no", "obs_id", "code"), "")).strip()

    def snapshot(rows: Sequence[Mapping[str, Any]]) -> Dict[str, Tuple[str, float]]:
        out: Dict[str, Tuple[str, float]] = {}
        for row in rows:
            k = key(row)
            if not k:
                continue
            out[k] = (
                sval(first_value(row, ("role",), "")).upper(),
                float(fval(first_value(row, ("observed",)), 0.0) or 0.0),
            )
        return out

    before = snapshot(before_rows)
    after = snapshot(after_rows)
    missing_after = sorted(set(before) - set(after))
    new_after = sorted(set(after) - set(before))
    role_changes = []
    observed_changes = []
    for k in sorted(set(before) & set(after)):
        br, bo = before[k]
        ar, ao = after[k]
        if br != ar:
            role_changes.append({"profile": k, "before_role": br, "after_role": ar})
        if abs(bo - ao) > 1.0e-7 * max(1.0, abs(bo), abs(ao)):
            observed_changes.append({"profile": k, "before_observed": bo, "after_observed": ao})
    passes = not (missing_after or new_after or role_changes or observed_changes)
    return {
        "passes": passes,
        "before_count": len(before),
        "after_count": len(after),
        "missing_after": missing_after,
        "new_after": new_after,
        "role_changes": role_changes,
        "observed_changes": observed_changes,
    }


def _geh20_transition_policy(config: Mapping[str, Any], policy_scope: str) -> Dict[str, Any] | None:
    """Return the reviewed GEH20 hysteresis/budget policy for one acceptance scope.

    Older releases/configurations intentionally fall back to the legacy discrete
    ``max_new_geh20`` count guard.  V2.4.9.5 opts in explicitly through
    ``geh20_transition_policy.mode == HYSTERESIS_BUDGET``.
    """
    raw = config.get("geh20_transition_policy", {}) if isinstance(config, Mapping) else {}
    if not isinstance(raw, Mapping) or sval(raw.get("mode", "")).upper() != "HYSTERESIS_BUDGET":
        return None
    scope = sval(policy_scope or "GENERATION").strip().upper()
    scope_key = "td" if scope.startswith("TD") else "generation"
    scoped = raw.get(scope_key, {}) or {}
    if not isinstance(scoped, Mapping):
        scoped = {}
    threshold = float(raw.get("threshold", 20.0))
    low = float(raw.get("hysteresis_low", threshold))
    high = float(raw.get("hysteresis_high", threshold))
    if not (0.0 <= low <= threshold <= high):
        raise ValueError("Invalid GEH20 hysteresis bounds")
    return {
        "mode": "HYSTERESIS_BUDGET",
        "scope": scope_key.upper(),
        "threshold": threshold,
        "hysteresis_low": low,
        "hysteresis_high": high,
        "max_material_new_geh20": int(scoped.get("max_material_new_geh20", 0)),
        "max_single_profile_geh_increase": float(scoped.get("max_single_profile_geh_increase", 0.0)),
        "max_total_new_geh20_excess": float(scoped.get("max_total_new_geh20_excess", 0.0)),
        "max_new_geh30": int(raw.get("max_new_geh30", config.get("max_new_geh30", 0))),
    }



# V2.4.9.12 is deliberately embedded in the numerical core.  The original
# draft imported a small policy module lazily from inside the live acceptance
# call.  In Visum, nested procedure/helper execution can change the effective
# import search path even though the launcher initially prioritised its release
# directory.  A safety policy must not depend on a late runtime module lookup.
# Keeping the implementation here makes the acceptance path self-contained;
# r1_15a2_guard_policy_v24912.py is a compatibility/audit wrapper only.
V24912_POLICY_ID = "V24912_BASELINE_RELATIVE_SEVERITY_BUDGET"
V24912_POLICY_LEVEL = "BASELINE_RELATIVE_BUDGET_V24912"


def _v24912_relative_degradation(before: Any, after: Any) -> float:
    b = float(fval(before, 0.0) or 0.0)
    a = float(fval(after, 0.0) or 0.0)
    if b <= EPS:
        return 0.0 if a <= b + EPS else float("inf")
    return max(0.0, (a - b) / b)


def rebase_severity_guard_v24912(
    guard: Mapping[str, Any],
    severity_policy: Mapping[str, Any],
    scoped_policy: Mapping[str, Any],
) -> Dict[str, Any]:
    """Reinterpret V2496 diagnostics using baseline-relative V24912 budgets.

    Existing bad profiles are grandfathered only as a starting condition.  A
    candidate is still rejected for excessive continuous-severity growth,
    excessive GEH40 count growth, a large single-profile jump, or a material
    worsening of an already-high profile.  Technical/model-state guards remain
    owned by their original fail-closed acceptance layers.
    """
    out: Dict[str, Any] = deepcopy(dict(guard))
    if str(severity_policy.get("policy_level", "")).upper() != V24912_POLICY_LEVEL:
        return out

    max_single = float(fval(severity_policy.get("max_single_profile_geh_increase"), 15.0) or 15.0)
    high_threshold = float(fval(severity_policy.get("high_geh_threshold"), 60.0) or 60.0)
    max_high_delta = float(fval(severity_policy.get("max_high_geh_increase"), 10.0) or 10.0)
    max_s20 = float(fval(scoped_policy.get("max_severity20_relative_degradation"), 0.0) or 0.0)
    max_s30 = float(fval(scoped_policy.get("max_severity30_relative_degradation"), 0.0) or 0.0)
    max_ge40 = int(ival(scoped_policy.get("max_geh40_net_count_increase"), 0) or 0)

    before = out.get("before_severity") if isinstance(out.get("before_severity"), Mapping) else {}
    after = out.get("after_severity") if isinstance(out.get("after_severity"), Mapping) else {}
    s20_deg = _v24912_relative_degradation(before.get("severity20"), after.get("severity20"))
    s30_deg = _v24912_relative_degradation(before.get("severity30"), after.get("severity30"))
    geh40_net = max(0, int(ival(after.get("geh_ge40"), 0) or 0) - int(ival(before.get("geh_ge40"), 0) or 0))

    high_rows: List[Dict[str, Any]] = []
    high_delta_violations: List[Dict[str, Any]] = []
    new_high_crossings: List[Dict[str, Any]] = []
    for raw in out.get("absolute_geh_ceiling_violations") or []:
        if not isinstance(raw, Mapping):
            continue
        row = dict(raw)
        bg = float(fval(row.get("before_geh"), 0.0) or 0.0)
        ag = float(fval(row.get("after_geh"), 0.0) or 0.0)
        inc = float(fval(row.get("geh_increase"), ag - bg) or 0.0)
        if ag > high_threshold + EPS:
            high_rows.append(row)
            if bg <= high_threshold + EPS:
                new_high_crossings.append(row)
            if inc > max_high_delta + EPS:
                high_delta_violations.append(row)

    # V24912 explicitly replaces only the two V2496 absolute/binary codes.
    violations = [
        str(code) for code in (out.get("violation_codes") or [])
        if str(code) not in {"NEW_GEH40_COUNT_EXCEEDED", "ABSOLUTE_GEH_CEILING_EXCEEDED"}
    ]
    if s20_deg > max_s20 + EPS:
        violations.append("V24912_SEVERITY20_BUDGET_EXCEEDED")
    if s30_deg > max_s30 + EPS:
        violations.append("V24912_SEVERITY30_BUDGET_EXCEEDED")
    if geh40_net > max_ge40:
        violations.append("V24912_GEH40_NET_COUNT_BUDGET_EXCEEDED")
    if high_delta_violations:
        violations.append("V24912_HIGH_GEH_DELTA_BUDGET_EXCEEDED")

    single = []
    for raw in out.get("single_profile_geh_increase_violations") or []:
        if not isinstance(raw, Mapping):
            continue
        row = dict(raw)
        inc = float(fval(row.get("geh_increase"),
                         float(fval(row.get("after_geh"), 0.0) or 0.0) -
                         float(fval(row.get("before_geh"), 0.0) or 0.0)) or 0.0)
        if inc > max_single + EPS:
            single.append(row)
    if single:
        violations.append("SINGLE_PROFILE_GEH_INCREASE_EXCEEDED")

    warnings = [str(x) for x in (out.get("warning_codes") or [])]
    if out.get("new_geh40"):
        warnings.append("V24912_GEH40_TRANSITION_WITHIN_NET_BUDGET")
    if new_high_crossings and not high_delta_violations:
        warnings.append("V24912_GEH60_THRESHOLD_CROSSING_DIAGNOSTIC_ONLY")
    if high_rows:
        warnings.append("V24912_EXISTING_HIGH_GEH_BASELINE_RELATIVE")

    violations = sorted(set(violations))
    warnings = sorted(set(warnings))
    out.update({
        "passes": not violations,
        "mode": "EARLY_EXPLORATION_BASELINE_RELATIVE_SEVERITY_V24912",
        "violation_codes": violations,
        "warning_codes": warnings,
        "severity20_relative_degradation": s20_deg,
        "severity30_relative_degradation": s30_deg,
        "geh40_net_count_increase": geh40_net,
        "new_geh60": new_high_crossings,
        "high_geh_rows": high_rows,
        "high_geh_delta_violations": high_delta_violations,
        "v24912_policy": {
            "policy_id": V24912_POLICY_ID,
            "policy_level": V24912_POLICY_LEVEL,
            "implementation_owner": "r1_15a2_core.py",
            "runtime_external_policy_import_required": False,
            "baseline_relative": True,
            "threshold_crossing_is_not_automatic_reject": True,
            "severity20_relative_degradation": s20_deg,
            "severity20_budget": max_s20,
            "severity30_relative_degradation": s30_deg,
            "severity30_budget": max_s30,
            "geh40_net_count_increase": geh40_net,
            "geh40_net_count_budget": max_ge40,
            "high_geh_threshold": high_threshold,
            "max_high_geh_increase": max_high_delta,
            "high_geh_delta_violation_count": len(high_delta_violations),
            "new_high_threshold_crossing_count": len(new_high_crossings),
            "max_single_profile_geh_increase": max_single,
        },
    })
    return out


def severity_transition_guard(
    before_rows: Sequence[Mapping[str, Any]],
    after_rows: Sequence[Mapping[str, Any]],
    config: Mapping[str, Any],
    policy_scope: str = "GENERATION",
) -> Dict[str, Any]:
    """Track severe-profile transitions with an exploratory and inherited mode.

    V2.4.9.6 EARLY_EXPLORATION makes GEH20/30 continuous diagnostics, GEH35
    a warning, and retains hard rejection only for new GEH40 crossings, a
    catastrophic single-profile jump, or an absolute ceiling violation.  After
    the configured early cycles the exact V2.4.9.5 hysteresis/budget contract
    is restored.
    """
    def key(row: Mapping[str, Any]) -> str:
        return sval(first_value(row, ("countlocation_no", "obs_id", "code"), "")).strip()

    bmap = {key(r): r for r in before_rows if key(r)}
    amap = {key(r): r for r in after_rows if key(r)}
    early = early_exploration_policy(config, policy_scope)
    if early is not None:
        sev = early["severity"]
        max_new40 = int(sev.get("max_new_geh40", 0))
        max_increase = float(sev.get("max_single_profile_geh_increase", 15.0))
        ceiling = float(sev.get("absolute_geh_ceiling", 60.0))
        power = float(sev.get("severity_score_power", 2.0))
        transitions = {20: [], 30: [], 35: [], 40: []}
        increase_violations = []
        ceiling_violations = []
        all_changes = []
        for k, b in bmap.items():
            a = amap.get(k)
            if a is None or sval(first_value(b, ("role",), "")).upper() != "CALIBRATION":
                continue
            bobs = float(fval(first_value(b, ("observed",)), 0.0) or 0.0)
            aobs = float(fval(first_value(a, ("observed",)), 0.0) or 0.0)
            if bobs <= 0.0 or aobs <= 0.0:
                continue
            bg = geh(float(fval(first_value(b, ("model",)), 0.0) or 0.0), bobs)
            ag = geh(float(fval(first_value(a, ("model",)), 0.0) or 0.0), aobs)
            row = {"profile": k, "before_geh": bg, "after_geh": ag,
                   "geh_increase": ag - bg}
            all_changes.append(row)
            for threshold in transitions:
                if bg < float(threshold) <= ag:
                    transitions[threshold].append(dict(row, threshold=float(threshold)))
            if ag - bg > max_increase + EPS:
                increase_violations.append(row)
            if ag > ceiling + EPS:
                ceiling_violations.append(row)
        before_metrics = geh_severity_metrics(before_rows, power)
        after_metrics = geh_severity_metrics(after_rows, power)
        def rel_gain(name: str) -> float:
            b = float(before_metrics.get(name, 0.0))
            a = float(after_metrics.get(name, 0.0))
            if b <= EPS:
                return 0.0 if a <= EPS else -float("inf")
            return (b - a) / b
        violations = []
        if len(transitions[40]) > max_new40:
            violations.append("NEW_GEH40_COUNT_EXCEEDED")
        if increase_violations:
            violations.append("SINGLE_PROFILE_GEH_INCREASE_EXCEEDED")
        if ceiling_violations:
            violations.append("ABSOLUTE_GEH_CEILING_EXCEEDED")
        result = {
            "passes": not violations,
            "mode": "EARLY_EXPLORATION_CONTINUOUS_SEVERITY",
            "policy_scope": early["scope"],
            "outer_cycle": early["outer_cycle"],
            "new_geh20": transitions[20],
            "new_geh30": transitions[30],
            "new_geh35_warning": transitions[35],
            "new_geh40": transitions[40],
            "material_new_geh20": transitions[20],
            "hysteresis_geh20": [],
            "before_severity": before_metrics,
            "after_severity": after_metrics,
            "severity20_relative_improvement": rel_gain("severity20"),
            "severity30_relative_improvement": rel_gain("severity30"),
            "geh20_count_reduction": int(before_metrics["geh_ge20"] - after_metrics["geh_ge20"]),
            "geh30_count_reduction": int(before_metrics["geh_ge30"] - after_metrics["geh_ge30"]),
            "max_new_geh40": max_new40,
            "max_single_profile_geh_increase": max_increase,
            "absolute_geh_ceiling": ceiling,
            "single_profile_geh_increase_violations": increase_violations,
            "absolute_geh_ceiling_violations": ceiling_violations,
            "warning_codes": (["NEW_GEH35_WARNING"] if transitions[35] else []),
            "violation_codes": violations,
        }
        if str(sev.get("policy_level", "")).upper() == V24912_POLICY_LEVEL:
            return rebase_severity_guard_v24912(result, sev, early["scoped"])
        return result

    policy = _geh20_transition_policy(config, policy_scope)
    threshold = float(policy["threshold"]) if policy else 20.0
    low = float(policy["hysteresis_low"]) if policy else threshold
    high = float(policy["hysteresis_high"]) if policy else threshold
    new20 = []
    hysteresis20 = []
    material20 = []
    new30 = []
    for k, b in bmap.items():
        a = amap.get(k)
        if a is None:
            continue
        if sval(first_value(b, ("role",), "")).upper() != "CALIBRATION":
            continue
        bobs = float(fval(first_value(b, ("observed",)), 0.0) or 0.0)
        bmod = float(fval(first_value(b, ("model",)), 0.0) or 0.0)
        aobs = float(fval(first_value(a, ("observed",)), 0.0) or 0.0)
        amod = float(fval(first_value(a, ("model",)), 0.0) or 0.0)
        if bobs <= 0.0 or aobs <= 0.0:
            continue
        bg = geh(bmod, bobs)
        ag = geh(amod, aobs)
        if bg < threshold <= ag:
            row = {
                "profile": k, "before_geh": bg, "after_geh": ag,
                "geh_increase": ag - bg,
                "excess_above_geh20": max(0.0, ag - threshold),
            }
            new20.append(row)
            if policy and bg >= low and ag <= high:
                hysteresis20.append(dict(row, classification="HYSTERESIS_CROSSING"))
            else:
                material20.append(dict(row, classification="MATERIAL_NEW_GEH20"))
        if bg < 30.0 <= ag:
            new30.append({
                "profile": k, "before_geh": bg, "after_geh": ag,
                "geh_increase": ag - bg,
                "excess_above_geh30": max(0.0, ag - 30.0),
            })
    if policy is None:
        passes = (len(new20) <= int(config.get("max_new_geh20", 999999))
                  and len(new30) <= int(config.get("max_new_geh30", 0)))
        return {
            "passes": passes, "mode": "LEGACY_DISCRETE_COUNT",
            "policy_scope": sval(policy_scope or "GENERATION").upper(),
            "new_geh20": new20, "new_geh30": new30,
            "hysteresis_geh20": [], "material_new_geh20": new20,
            "violation_codes": ([] if passes else ["LEGACY_NEW_GEH_COUNT_EXCEEDED"]),
        }
    max_count = int(policy["max_material_new_geh20"])
    max_single = float(policy["max_single_profile_geh_increase"])
    max_total_excess = float(policy["max_total_new_geh20_excess"])
    max_new30 = int(policy["max_new_geh30"])
    single_violations = [r for r in material20 if float(r["geh_increase"]) > max_single + EPS]
    total_excess = float(sum(float(r["excess_above_geh20"]) for r in material20))
    violation_codes = []
    if len(material20) > max_count:
        violation_codes.append("MATERIAL_NEW_GEH20_COUNT_EXCEEDED")
    if single_violations:
        violation_codes.append("SINGLE_PROFILE_GEH_INCREASE_EXCEEDED")
    if total_excess > max_total_excess + EPS:
        violation_codes.append("TOTAL_NEW_GEH20_EXCESS_EXCEEDED")
    if len(new30) > max_new30:
        violation_codes.append("NEW_GEH30_COUNT_EXCEEDED")
    return {
        "passes": not violation_codes, "mode": policy["mode"],
        "policy_scope": policy["scope"], "threshold": threshold,
        "hysteresis_low": low, "hysteresis_high": high,
        "new_geh20": new20, "hysteresis_geh20": hysteresis20,
        "material_new_geh20": material20, "new_geh30": new30,
        "material_new_geh20_count": len(material20),
        "max_material_new_geh20": max_count,
        "single_profile_geh_increase_limit": max_single,
        "single_profile_geh_increase_violations": single_violations,
        "total_new_geh20_excess": total_excess,
        "max_total_new_geh20_excess": max_total_excess,
        "max_new_geh30": max_new30, "violation_codes": violation_codes,
    }

def idp_metrics(summary: Mapping[str, Any]) -> Dict[str, Any]:
    vals = []
    component_rows = summary.get("component_dist_summary_rows", []) if isinstance(summary, Mapping) else []
    for r in component_rows:
        fam = sval(r.get("family", "")).upper()
        if fam == "SERV":
            fam = "SERVICE"
        if fam not in ("WORK", "SERVICE", "LONG"):
            continue
        if "ACTIVE" not in sval(r.get("target_status", "")).upper() and fam != "LONG":
            continue
        model = fval(r.get("mean_model_conditioned"), None)
        target = fval(r.get("mean_target"), None)
        l1 = fval(r.get("l1_distance_half"), None)
        rmse_share = fval(r.get("rmse_share"), None)
        if model is None or target is None or target <= 0:
            continue
        mean_rel = abs(model - target) / target
        # Distribution L1 is the preferred behavioral guard; the relative mean
        # error is retained as a second, interpretable diagnostic.
        primary = l1 if l1 is not None else mean_rel
        vals.append({
            "component": r.get("component", r.get("code", "")),
            "family": fam,
            "primary_error": primary,
            "l1_distance_half": l1,
            "rmse_share": rmse_share,
            "relative_mean_error": mean_rel,
        })
    errors = [x["primary_error"] for x in vals]
    mean_errors = [x["relative_mean_error"] for x in vals]
    return {
        "n": len(errors),
        "component_set": sorted(sval(x["component"]) for x in vals),
        "mean_primary_error": float(sum(errors) / len(errors)) if errors else 0.0,
        "max_primary_error": float(max(errors)) if errors else 0.0,
        "mean_relative_mean_error": float(sum(mean_errors) / len(mean_errors)) if mean_errors else 0.0,
        "max_relative_mean_error": float(max(mean_errors)) if mean_errors else 0.0,
        # Backward-compatible aliases used by the acceptance config/report.
        "mean_relative_error": float(sum(errors) / len(errors)) if errors else 0.0,
        "max_relative_error": float(max(errors)) if errors else 0.0,
        "components": vals,
    }


def acceptance_decision(
    before_12d_rows: Sequence[Mapping[str, Any]],
    after_12d_rows: Sequence[Mapping[str, Any]],
    before_11d_summary: Mapping[str, Any],
    after_11d_summary: Mapping[str, Any],
    config: Mapping[str, Any],
    policy_scope: str = "GENERATION",
) -> Dict[str, Any]:
    before_cal = csd_metrics(before_12d_rows, "CALIBRATION", True)
    after_cal = csd_metrics(after_12d_rows, "CALIBRATION", True)
    before_val = csd_metrics(before_12d_rows, "VALIDATION", True)
    after_val = csd_metrics(after_12d_rows, "VALIDATION", True)
    before_idp = idp_metrics(before_11d_summary)
    after_idp = idp_metrics(after_11d_summary)
    early = early_exploration_policy(config, policy_scope)
    protect = protected_profile_guard(before_12d_rows, after_12d_rows, config, policy_scope)
    observation_guard = observation_set_guard(before_12d_rows, after_12d_rows)
    severity_guard = severity_transition_guard(before_12d_rows, after_12d_rows, config, policy_scope)
    reasons = []
    objective_metric = csd_objective_metric(config)
    objective_key = csd_objective_key(config)
    obj_before = csd_objective_value(before_cal, config)
    obj_after = csd_objective_value(after_cal, config)
    rel_improvement = ((obj_before - obj_after) / max(EPS, abs(obj_before))
                       if math.isfinite(obj_before) else -float("inf"))
    acceptance_path = "INHERITED_MONOTONIC_OBJECTIVE"
    nonmonotonic = False
    generation_gate_passes = True
    if early is not None and early["scope"] == "GENERATION":
        scoped = early["scoped"]
        epsilon = float(scoped.get("positive_improvement_epsilon", 1.0e-12))
        max_degradation = float(scoped.get("max_cal_relative_degradation_for_severity_tradeoff", 0.02))
        min_s20 = float(scoped.get("min_severity20_relative_improvement", 0.01))
        min_s30 = float(scoped.get("min_severity30_relative_improvement", 0.01))
        min_count20 = int(scoped.get("min_geh20_count_reduction", 3))
        min_count30 = int(scoped.get("min_geh30_count_reduction", 1))
        if math.isfinite(obj_after) and rel_improvement > epsilon:
            acceptance_path = "EARLY_EXPLORATION_ANY_POSITIVE_WEIGHTED_GEH"
        else:
            degradation = max(0.0, -rel_improvement)
            severity_improved = (
                float(severity_guard.get("severity20_relative_improvement", -float("inf"))) >= min_s20
                or float(severity_guard.get("severity30_relative_improvement", -float("inf"))) >= min_s30
                or int(severity_guard.get("geh20_count_reduction", 0)) >= min_count20
                or int(severity_guard.get("geh30_count_reduction", 0)) >= min_count30
            )
            if math.isfinite(obj_after) and degradation <= max_degradation + EPS and severity_improved:
                acceptance_path = "EARLY_EXPLORATION_NONMONOTONIC_SEVERITY_TRADEOFF"
                nonmonotonic = True
            else:
                generation_gate_passes = False
                reasons.append(csd_objective_reason(config))
    elif early is not None and early["scope"] == "SUPPLY":
        # Route-choice ADDVAL tuning must improve the live CAL weighted-GEH
        # objective, but no longer needs the inherited 0.1% materiality wall.
        # Large local trade-offs are handled by the dedicated baseline-relative
        # severity and IDP budgets below, while the controller independently
        # requires a positive fixed-reference shared-objective improvement.
        scoped = early["scoped"]
        epsilon = float(scoped.get("positive_improvement_epsilon", 1.0e-12))
        if math.isfinite(obj_after) and rel_improvement > epsilon:
            acceptance_path = "SUPPLY_ROUTE_CHOICE_ANY_POSITIVE_WEIGHTED_GEH"
        else:
            generation_gate_passes = False
            reasons.append(csd_objective_reason(config))
    elif not math.isfinite(obj_after) or rel_improvement < float(config.get("min_cal_objective_relative_improvement", 0.001)):
        generation_gate_passes = False
        reasons.append(csd_objective_reason(config))
    if not observation_guard.get("passes", False):
        reasons.append("OBSERVATION_AUTHORITY_CHANGED")
    if not severity_guard.get("passes", False):
        reasons.append("NEW_SEVERE_GEH_PROFILE")
    if not protect.get("passes", False):
        reasons.append("PROTECTED_PROFILE_GUARD_FAILED")
    idp_mean_degradation = float(after_idp.get("mean_relative_error", 0.0)) - float(before_idp.get("mean_relative_error", 0.0))
    idp_max_degradation = float(after_idp.get("max_relative_error", 0.0)) - float(before_idp.get("max_relative_error", 0.0))
    if before_idp.get("component_set") != after_idp.get("component_set"):
        reasons.append("IDP_COMPONENT_AUTHORITY_CHANGED")
    idp_mean_limit = float(config.get("idp_max_mean_degradation", 0.005))
    idp_component_limit = float(config.get("idp_max_component_degradation", 0.02))
    if early is not None and early["scope"] == "SUPPLY":
        idp_mean_limit = float(early["scoped"].get("max_idp_mean_degradation", idp_mean_limit))
        idp_component_limit = float(early["scoped"].get("max_idp_component_degradation", idp_component_limit))
    if idp_mean_degradation > idp_mean_limit:
        reasons.append("IDP_MEAN_DEGRADED")
    if idp_max_degradation > idp_component_limit:
        reasons.append("IDP_COMPONENT_DEGRADED")
    return {
        "accepted": not reasons, "reasons": reasons,
        "active_acceptance_stage": (("SUPPLY_ROUTE_CHOICE_EXPLORATION" if early.get("scope") == "SUPPLY" else "EARLY_EXPLORATION") if early is not None else "INHERITED"),
        "acceptance_policy_scope": sval(policy_scope).upper(),
        "acceptance_path": acceptance_path,
        "generation_primary_gate_passes": generation_gate_passes,
        "exploration_nonmonotonic_accepted": bool(nonmonotonic and not reasons),
        "early_exploration_policy": early,
        "cal_before": before_cal, "cal_after": after_cal,
        "validation_before_report_only": before_val,
        "validation_after_report_only": after_val,
        "validation_used_for_design_or_acceptance": False,
        "idp_before": before_idp, "idp_after": after_idp,
        "idp_mean_degradation": idp_mean_degradation,
        "idp_max_degradation": idp_max_degradation,
        "idp_mean_degradation_limit": idp_mean_limit,
        "idp_component_degradation_limit": idp_component_limit,
        "protected_guard": protect, "observation_set_guard": observation_guard,
        "severity_transition_guard": severity_guard,
        "cal_objective_metric": objective_metric, "cal_objective_key": objective_key,
        "cal_objective_before": obj_before, "cal_objective_after": obj_after,
        "cal_objective_relative_improvement": rel_improvement,
    }


